function frame = packFlightFrame(sequence,timeSeconds,accel,gyro, ...
        imuValid,tofM,tofValid,tofRangeStatus,flowDelta,flowQuality, ...
        flowStatus,flowShutter,xy,flowUsed,mag,magValid,orientation, ...
        orientationValid,heightM,heightValid,flowDeltaEN,motorCommands, ...
        motorValid,flightState,acceptedCommandSequence)
%PACKFLIGHTFRAME SFI6: SFI5 plus Stateflow state and accepted command ID.
base = legacyframe.packMotorFrame(sequence,timeSeconds,accel,gyro, ...
    imuValid,tofM,tofValid,tofRangeStatus,flowDelta,flowQuality, ...
    flowStatus,flowShutter,xy,flowUsed,mag,magValid,orientation, ...
    orientationValid,heightM,heightValid,flowDeltaEN,motorCommands,motorValid);
frame = zeros(114,1,'uint8');
frame(1:109) = base(1:109);
frame(1:4) = uint8('SFI6');
frame(110) = uint8(flightState);
frame(111:112) = reshape(typecast(uint16(acceptedCommandSequence),'uint8'),2,1);
frame(113:114) = reshape(typecast(imu.crc16(frame(1:112)),'uint8'),2,1);
end
