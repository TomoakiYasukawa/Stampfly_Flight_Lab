function report=verify_final_pipeline()
%VERIFY_FINAL_PIPELINE Compare the reorganized root wiring to the first flight.
% 現在の最上位の実配線をコピー。過去のリプレイモデルは使わない。
root=stampfly_project_root();model='StampFly_Official_FlightTest400';
stages=load(fullfile(root,'tests','root_reorganization_ids.mat')).result;
snapshot=load(fullfile(root,'tests','model_reorganization_before.mat')).snapshot;
snapshot.InitialFile=fullfile(root,'archive','snapshots','FlightTest_disk_before_sensor_blocks_20261015_092114.slx');
[~,baseline]=fileparts(snapshot.InitialFile);open_system(snapshot.InitialFile);
harness='FinalPipelineEquivalence400';if bdIsLoaded(harness),close_system(harness,0);end
new_system(harness);open_system(harness);
selected={stages.Correction,stages.Estimation,stages.Control,stages.Context.ID,stages.CommandPreparation.ID};
inputGroups=[reorg.group('RawIMU',{[stages.IMUSensor.ID '.y1']},{'RawIMU'}), ...
    reorg.group('BottomRange',{[stages.BottomSensor.ID '.y1']},{'BottomRange'}), ...
    reorg.group('BatteryVoltage',{[stages.BatterySensor.ID '.y1']},{'BatteryVoltage'}), ...
    reorg.group('JoystickCommand',{[stages.JoystickSensor.ID '.y1']},{'JoystickCommand'}), ...
    reorg.group('Dt',{'blk_4.y2'},{'Dt'})];
names={'Duty','Counts','Mode','Angles','AngularRate','Altitude','Velocity','Quaternion','SensorFlags', ...
    'ControlDiagnostics','SensorDiagnostics','PreviousMode','AltitudeEnabled','Connected','FlipPhase'};
outputGroups=[reorg.group('MotorCommand',{[stages.Control '.y1']},{'MotorCommand'}), ...
    reorg.group('FlightStatus',{[stages.Control '.y2']},{'FlightStatus'}), ...
    reorg.group('Attitude',{[stages.Estimation '.y1']},{'Attitude'}), ...
    reorg.group('VerticalMotion',{[stages.Estimation '.y2']},{'VerticalMotion'}), ...
    reorg.group('SensorStatus',{[stages.Estimation '.y3']},{'SensorStatus'})];
pipeline=reorg.groupCopy(model,'root','root',selected,'CurrentRootPipeline',inputGroups,outputGroups,harness);
inputNames={'Acceleration','AngularRate','BottomDistanceMm','BottomFresh','BatteryVoltage', ...
    'Sticks','ArmButton','NewPacket','AHRSRequest','Dt','FlipButton'};
types={'single','single','int16','uint8','single','single','uint8','uint8','uint8','single','uint8'};
dims=[3 3 1 1 1 6 1 1 1 1 1];
ops={reorg.configure(['config:' harness],struct('Solver','FixedStepDiscrete','FixedStep','.0025', ...
    'StopTime','1','SaveOutput','on','OutputSaveName','yout','SaveFormat','Dataset')), ...
    reorg.add(reorg.path(baseline,'blk_38'),'InitialFlightAlgorithm','old'), ...
    reorg.add('BusCreator','RawIMUBus','imu',struct('Inputs','2')), ...
    reorg.add('BusCreator','BottomRangeBus','bottom',struct('Inputs','2')), ...
    reorg.add('BusCreator','JoystickCommandBus','joystick',struct('Inputs','5'))};
for k=1:11
    ref=['i' num2str(k)];ops{end+1}=reorg.add('Inport',inputNames{k},ref,struct('Port',num2str(k), ...
        'OutDataTypeStr',types{k},'PortDimensions',num2str(dims(k)),'SampleTime','.0025'));
    ops{end+1}=reorg.wire(['#' ref '.y1'],sprintf('#old.u%d',k));
end
ops=[ops,{reorg.wire('#i1.y1','#imu.u1','Acceleration'), ...
    reorg.wire('#i2.y1','#imu.u2','AngularRate'), ...
    reorg.wire('#imu.y1',[pipeline.ID '.u1'],'RawIMU'), ...
    reorg.wire('#i3.y1','#bottom.u1','DistanceMm'),reorg.wire('#i4.y1','#bottom.u2','Fresh'), ...
    reorg.wire('#bottom.y1',[pipeline.ID '.u2'],'BottomRange'), ...
    reorg.wire('#i5.y1',[pipeline.ID '.u3'],'BatteryVoltage'), ...
    reorg.wire('#i6.y1','#joystick.u1','Sticks'),reorg.wire('#i7.y1','#joystick.u2','ArmButton'), ...
    reorg.wire('#i8.y1','#joystick.u3','NewPacket'),reorg.wire('#i9.y1','#joystick.u4','AHRSRequest'), ...
    reorg.wire('#i11.y1','#joystick.u5','FlipButton'), ...
    reorg.wire('#joystick.y1',[pipeline.ID '.u4'],'JoystickCommand'), ...
    reorg.wire('#i10.y1',[pipeline.ID '.u5'],'Dt'), ...
    reorg.add('BusSelector','MotorResults','motorResults',struct('OutputSignals','Duty,Counts')), ...
    reorg.add('BusSelector','FlightResults','flightResults',struct('OutputSignals','Mode,PreviousMode,AltitudeEnabled,Connected,FlipPhase,Diagnostics')), ...
    reorg.add('BusSelector','AttitudeResults','attitudeResults',struct('OutputSignals','Angles,Quaternion,AngularRate')), ...
    reorg.add('BusSelector','VerticalResults','verticalResults',struct('OutputSignals','Altitude,Velocity')), ...
    reorg.add('BusSelector','SensorResults','sensorResults',struct('OutputSignals','Flags,Diagnostics')), ...
    reorg.wire([pipeline.ID '.y1'],'#motorResults.u1'), ...
    reorg.wire([pipeline.ID '.y2'],'#flightResults.u1'), ...
    reorg.wire([pipeline.ID '.y3'],'#attitudeResults.u1'), ...
    reorg.wire([pipeline.ID '.y4'],'#verticalResults.u1'), ...
    reorg.wire([pipeline.ID '.y5'],'#sensorResults.u1')}];
endpoints={'#motorResults.y1','#motorResults.y2','#flightResults.y1','#attitudeResults.y1', ...
    '#attitudeResults.y3','#verticalResults.y1','#verticalResults.y2','#attitudeResults.y2', ...
    '#sensorResults.y1','#flightResults.y6','#sensorResults.y2','#flightResults.y2', ...
    '#flightResults.y3','#flightResults.y4','#flightResults.y5'};
for k=1:15
    a=['oldOut' num2str(k)];b=['newOut' num2str(k)];
    ops=[ops,{reorg.add('Outport',['Initial' names{k}],a,struct('Port',num2str(2*k-1))), ...
        reorg.add('Outport',['Current' names{k}],b,struct('Port',num2str(2*k))), ...
        reorg.wire(sprintf('#old.y%d',k),['#' a '.u1']), ...
        reorg.wire(endpoints{k},['#' b '.u1'])}];
end
reorg.edit(harness,'root',ops,'full');save_system(harness,stampfly_model_file(harness));
cases={'BootTakeoffHoverLanding','ModeAndFlip','SensorTimingAndInterruptions'};
report=struct('Baseline',snapshot.InitialFile,'CurrentModel',get_param(model,'FileName'),'Outputs',{names},'TotalSamples',0);
report.Stage='Saved final root wiring after compact logging and signal naming';
for c=1:numel(cases)
    trace=load(fullfile(root,'tests',['reorganized_core_' cases{c} '.mat']),'values','t');dataset=Simulink.SimulationData.Dataset;
    for k=1:11,ts=timeseries(trace.values{k},trace.t);ts.DataInfo.Interpolation=tsdata.interpolation('zoh');dataset=dataset.addElement(ts);end
    in=Simulink.SimulationInput(harness);in=in.setVariable('inf',builtin('inf'));in=in.setExternalInput(dataset);
    in=in.setModelParameter('StopTime',num2str(trace.t(end),17));out=sim(in);
    r=struct('Samples',numel(trace.t),'MismatchCounts',zeros(1,15),'MaxErrors',zeros(1,15),'TypesMatch',true,'SizesMatch',true);
    for k=1:15
        a=out.yout{2*k-1}.Values.Data;b=out.yout{2*k}.Values.Data;
        r.TypesMatch=r.TypesMatch&&strcmp(class(a),class(b));r.SizesMatch=r.SizesMatch&&isequal(size(a),size(b));
        assert(r.SizesMatch);r.MismatchCounts(k)=nnz(a~=b & ~(isnan(a)&isnan(b)));r.MaxErrors(k)=max(abs(double(a)-double(b)),[],'all');
    end
    report.(cases{c})=r;report.TotalSamples=report.TotalSamples+numel(trace.t);
    save(fullfile(root,'tests',['final_pipeline_' cases{c} '.mat']),'r','out');disp(cases{c});disp(r);
    assert(r.TypesMatch&&all(r.MismatchCounts==0),'official:FinalPipelineNotEquivalent','%s differs from initial model.',cases{c});
end
save(fullfile(root,'tests','final_pipeline_equivalence.mat'),'report');
end
