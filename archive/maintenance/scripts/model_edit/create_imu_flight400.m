function create_imu_flight400(stage)
%CREATE_IMU_FLIGHT400 Copy the basic model and use the standard IMU Filter.
% Structural changes are applied through model_edit. The source is not saved.
if nargin==0,stage='all';end
root=stampfly_project_root();ensure_simulink_toolkit();
model='StampFly_IMU400';
if strcmp(stage,'all')
    create_imu_flight400('copy');
    create_imu_flight400('replace');
    return
end
if strcmp(stage,'copy')
    assert(~isfile(stampfly_model_file(model)),'imuflight:AlreadyExists','IMU model already exists.');
    open_system(fullfile(root,'archive','aircraft','archive/aircraft/StampFly_Basic400.slx'));
    assert(strcmp(get_param('StampFly_Basic400','Dirty'),'off'),'imuflight:UnsavedSource','Save the source before copying.');
    copyfile(fullfile(root,'archive','aircraft','archive/aircraft/StampFly_Basic400.slx'),stampfly_model_file(model));
    open_system(stampfly_model_file(model));
    reorg.edit(model,'root',{reorg.configure(['config:' model],struct( ...
        'InitFcn','init_imu_flight;', ...
        'PostLoadFcn',sprintf("run(fullfile(fileparts(get_param('%s','FileName')),'config','startup.m'));",model), ...
        'Description','StampFly 400 Hz basic flight using IMU Filter attitude and bias-corrected angular rate.'))},'incremental');
    init_imu_flight();save_system(model);
    fprintf('IMU400_COPY_SAVED\n');return
end
assert(ismember(stage,{'replace','finish'}));
open_system(stampfly_model_file(model));init_imu_flight();
scope='blk_2231';disp(model_read(model,scope,'0'));
if strcmp(stage,'finish')
    attitude=namedID(model,scope,'IMUAttitude400');
    state=namedID(model,attitude,'FusionState');
    inputs=namedID(model,attitude,'FilterInputs');
    outputs=namedID(model,attitude,'FlightOutputs');
    update=namedID(model,state,'UpdateWhenReady');
    filter=namedID(model,update,'IMU Filter');
    finishModel(root,model,scope,attitude,state,inputs,outputs,update,filter);
    return
end
% Rebuild only our unfinished wrapper when resuming a checkpoint. The old
% estimator stays connected until the replacement is structurally complete.
old=find_system(reorg.path(model,scope),'SearchDepth',1,'Name','MadgwickAttitude');
assert(numel(old)<=1);
unfinished=find_system(reorg.path(model,scope),'SearchDepth',1,'Name','IMUAttitude400');
if ~isempty(unfinished)
    assert(numel(unfinished)==1);
    reorg.edit(model,scope,{struct('op','delete','target',reorg.id(unfinished{1}))},'incremental');
end
load_system('simulink');
resetLibrary=Simulink.ID.getFullName('simulink:144:70');
enableLibrary=Simulink.ID.getFullName('simulink:144:13');
resetParameters=get_param(resetLibrary,'DialogParameters');
disp(resetParameters.ResetTriggerType);
reply=reorg.edit(model,scope,{struct('op','create_subsystem','name','IMUAttitude400','ref','attitude', ...
    'interface',struct('inputs',{{'AngularRate','AccelerationG','PreviousMode','AttitudeReset'}}, ...
    'outputs',{{'Angles','Quaternion','CorrectedAngularRate'}}))},'incremental');
attitude=reorg.created(reply,'attitude');[ip,op]=reorg.ports(model,attitude);
ops={reorg.add('MATLAB Function','FilterInputs','inputs'), ...
    struct('op','create_subsystem','name','FusionState','ref','state', ...
    'interface',struct('inputs',{{'Accel','Gyro','Reset'}},'outputs',{{'Orientation','AngularVelocity'}})), ...
    reorg.add('MATLAB Function','FlightOutputs','outputs')};
% Set function bodies before connecting their nondefault ports.
reply=reorg.edit(model,attitude,ops,'full');
inputs=reorg.created(reply,'inputs');state=reorg.created(reply,'state');outputs=reorg.created(reply,'outputs');
writeFunction(model,inputs,fileread(fullfile(root,'code','model_algorithms','IMUFilterInputs.m')));
writeFunction(model,outputs,fileread(fullfile(root,'code','model_algorithms','IMUFlightOutputs.m')));
[si,so]=reorg.ports(model,state);
reply=reorg.edit(model,state,{reorg.add(enableLibrary,'Enable','enable',struct('StatesWhenEnabling','held')), ...
    reorg.configure(state,struct('TreatAsAtomicUnit','on')), ...
    struct('op','create_subsystem','name','UpdateWhenReady','ref','update', ...
    'interface',struct('inputs',{{'Accel','Gyro'}},'outputs',{{'Orientation','AngularVelocity'}}))},'full');
update=reorg.created(reply,'update');
[ui,uo]=reorg.ports(model,update);
filterParams=struct('DispRefFrame','NED','OrientationFormat','quaternion','DecimationFactor','1', ...
    'InitialProcessNoise','IMUFlight.InitialProcessNoise','AccelerometerNoise','IMUFlight.AccelerometerNoise', ...
    'GyroscopeNoise','IMUFlight.GyroscopeNoise','GyroscopeDriftNoise','IMUFlight.GyroscopeDriftNoise', ...
    'LinearAccelerationNoise','IMUFlight.LinearAccelerationNoise', ...
    'LinearAccelerationDecayFactor','IMUFlight.LinearAccelerationDecayFactor','SimulateUsing','Code generation');
reply=reorg.edit(model,update,{reorg.add(resetLibrary,'Reset','resetPort',struct('ResetTriggerType','level')), ...
    reorg.add('mspfiltlib/IMU Filter','IMU Filter','filter',filterParams), ...
    reorg.wire([ui{1} '.y1'],'#filter.u1'),reorg.wire([ui{2} '.y1'],'#filter.u2'), ...
    reorg.wire('#filter.y1',[uo{1} '.u1']),reorg.wire('#filter.y2',[uo{2} '.u1']), ...
    reorg.configure(uo{1},struct('InitialOutput','single([1 0 0 0])')), ...
    reorg.configure(uo{2},struct('InitialOutput','single([0 0 0])'))},'full');
filter=reorg.created(reply,'filter');
reorg.edit(model,state,{reorg.wire([si{1} '.y1'],[update '.u1']), ...
    reorg.wire([si{2} '.y1'],[update '.u2']),reorg.wire([si{3} '.y1'],[update '.Reset']), ...
    reorg.wire([update '.y1'],[so{1} '.u1']),reorg.wire([update '.y2'],[so{2} '.u1']), ...
    reorg.configure(so{1},struct('InitialOutput','single([1 0 0 0])','OutputWhenDisabled','held')), ...
    reorg.configure(so{2},struct('InitialOutput','single([0 0 0])','OutputWhenDisabled','held'))},'full');
reorg.edit(model,attitude,{reorg.wire([ip{1} '.y1'],[inputs '.u1']), ...
    reorg.wire([ip{2} '.y1'],[inputs '.u2']),reorg.wire([ip{3} '.y1'],[inputs '.u3']), ...
    reorg.wire([ip{4} '.y1'],[inputs '.u4']), ...
    reorg.wire([inputs '.y1'],[state '.u1'],'AccelMps2'), ...
    reorg.wire([inputs '.y2'],[state '.u2'],'GyroRps'), ...
    reorg.wire([inputs '.y4'],[state '.u3'],'PendingReset'), ...
    reorg.wire([inputs '.y3'],[state '.Enable']), ...
    reorg.wire([state '.y1'],[outputs '.u1']),reorg.wire([state '.y2'],[outputs '.u2']), ...
    reorg.wire([inputs '.y3'],[outputs '.u3']),reorg.wire([ip{4} '.y1'],[outputs '.u4']), ...
    reorg.wire([ip{1} '.y1'],[outputs '.u5']), ...
    reorg.wire([outputs '.y1'],[op{1} '.u1'],'Angles'), ...
    reorg.wire([outputs '.y2'],[op{2} '.u1'],'Quaternion'), ...
    reorg.wire([outputs '.y3'],[op{3} '.u1'],'AngularRate')},'full');
reorg.edit(model,scope,{reorg.wire('blk_2241.y2',[attitude '.u1']), ...
    reorg.wire('blk_2241.y1',[attitude '.u2']),reorg.wire('blk_2240.y1',[attitude '.u3']), ...
    reorg.wire('blk_2240.y4',[attitude '.u4']), ...
    reorg.wire([attitude '.y1'],'blk_2256.u1'),reorg.wire([attitude '.y2'],'blk_2257.u1'), ...
    reorg.wire([attitude '.y3'],'blk_2239.u1')},'incremental');
if ~isempty(old),reorg.edit(model,scope,{struct('op','delete','target','blk_2243')},'incremental');end
finishModel(root,model,scope,attitude,state,inputs,outputs,update,filter);
end
function finishModel(root,model,scope,attitude,state,inputs,outputs,update,filter)
% Keep IMU Filter's matrix-row interface explicit. Otherwise an ERT compile
% can infer 1-D vectors from the surrounding flight bus and initial values.
[ui,uo]=reorg.ports(model,update);[si,so]=reorg.ports(model,state);
reorg.edit(model,update,{reorg.configure(ui{1},struct('PortDimensions','[1 3]')), ...
    reorg.configure(ui{2},struct('PortDimensions','[1 3]')), ...
    reorg.configure(uo{1},struct('PortDimensions','[1 4]')), ...
    reorg.configure(uo{2},struct('PortDimensions','[1 3]'))},'incremental');
reorg.edit(model,state,{reorg.configure(si{1},struct('PortDimensions','[1 3]')), ...
    reorg.configure(si{2},struct('PortDimensions','[1 3]')), ...
    reorg.configure(so{1},struct('PortDimensions','[1 4]')), ...
    reorg.configure(so{2},struct('PortDimensions','[1 3]'))},'incremental');
logger=find_system(model,'LookUnderMasks','all','BlockType','MATLABSystem','System','basic.ExtendedLogger50');
assert(numel(logger)==1);loggerID=reorg.id(logger{1});loggerScope=reorg.id(get_param(logger{1},'Parent'));
reorg.edit(model,loggerScope,{reorg.configure(loggerID,struct('FirmwareRevision','uint32(1701)'))},'incremental');
note=sprintf('姿勢・角速度推定（400 Hz）\nIMU Filter: 起動時校正後の加速度・角速度から姿勢と残留バイアスを推定。\nPIDにはバイアス補正済み角速度を渡す。高度Kalmanと離着陸・PID係数は基礎版を維持。');
reorg.edit(model,scope,{reorg.configure('blk_3297',struct('Description',note, ...
    'MaskDisplay','disp(''IMU Filter / 400 Hz'');')), ...
    reorg.configure(attitude,struct('Description', ...
    'Standard IMU Filter: NED frame, 400 Hz, attitude and residual-bias-corrected gyro. Startup calibration, mode gating and flight conventions are retained.'))},'incremental');
assert(strcmp(get_param(reorg.path(model,inputs),'MATLABFunctionConfiguration').FunctionScript, ...
    fileread(fullfile(root,'code','model_algorithms','IMUFilterInputs.m'))));
assert(strcmp(get_param(reorg.path(model,outputs),'MATLABFunctionConfiguration').FunctionScript, ...
    fileread(fullfile(root,'code','model_algorithms','IMUFlightOutputs.m'))));
for group={update,state,attitude,scope,'root'}
    result=char(model_check(model,group{1},'["all"]'));fprintf('%s\n',result);
    assert(~contains(result,'severity: error'),'imuflight:Connectivity','Incomplete scope %s',group{1});
end
save_system(model);
report=struct('Model',model,'SourceModel','StampFly_Basic400','AttitudeBlock',attitude, ...
    'FusionStateBlock',state,'UpdateBlock',update,'FilterBlock',filter,'InputBlock',inputs, ...
    'OutputBlock',outputs,'SourceSaved',false,'FirmwareRevision',1701);
fid=fopen(fullfile(root,'docs','history','imu_flight_structure.json'),'w','n','UTF-8');assert(fid>=0);
fprintf(fid,'%s\n',jsonencode(report,'PrettyPrint',true));fclose(fid);
fprintf('IMU400_REPLACEMENT_SAVED\n');
end
function id=namedID(model,scope,name)
blocks=find_system(reorg.path(model,scope),'SearchDepth',1,'Name',name);
assert(numel(blocks)==1,'imuflight:MissingBlock','Expected one %s block.',name);
id=reorg.id(blocks{1});
end
function writeFunction(model,id,body)
disp(model_read(model,id,'0'));
config=get_param(reorg.path(model,id),'MATLABFunctionConfiguration');
config.FunctionScript=body;
disp(model_read(model,id,'0'));
end
