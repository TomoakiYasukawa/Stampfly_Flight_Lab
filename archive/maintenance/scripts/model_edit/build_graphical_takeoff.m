function report=build_graphical_takeoff()
%BUILD_GRAPHICAL_TAKEOFF Native states for parking, ramp, hover and landing.
model='StampFly_Official_FlightTest400';id='blk_126';
description=sprintf(['離陸・ホバリング・着陸の指令生成（400 Hz）\n' ...
    'Parking: 高度0.5 m/推力0へ初期化。自動離陸: 0〜499周期は3.8 V基準、500〜999周期は実電圧トリム。\n' ...
    'AutoHover: 1000周期後の基準推力。目標高度0.05〜1.8 m、スティックで更新。\n' ...
    'ManualAltitude/AutoHover/Landingの遷移条件は図に表示。演算順・状態保持・AltFlag保持は公式互換。\n' ...
    'Chart内にMATLAB関数は置かない。']);
reorg.chartInterface(model,id,description);
ops={reorg.data('Alt','single','.5'),reorg.data('Base','single','0'),reorg.data('Counter','uint16','0'), ...
    reorg.data('RangeOld','uint8','0'),reorg.data('landingActive','boolean','false'), ...
    reorg.data('History','single','zeros(10,1)','[10 1]'),reorg.data('AltFlag','boolean','false'), ...
    reorg.data('ControlMode','uint8','0'),reorg.data('th','single','0'),reorg.data('j','double','0'), ...
    reorg.add('Event','step','step',struct('Name','step','Scope','Local')), ...
    reorg.add('State','CommandPhases','phases',struct('LabelString','CommandPhases', ...
    'ExecutionOrder',1,'Decomposition','EXCLUSIVE_OR','Position',[40 50 1450 1050]))};
reply=reorg.edit(model,id,ops,'full');phases=reorg.created(reply,'phases');
names={'Hold','Parking','ManualAltitude','TakeoffReference','TakeoffBattery','AutoHover','Landing'};
trimV='(-single(.2448)*voltage+single(1.5892))';trim38='(-single(.2448)*single(3.8)+single(1.5892))';
autoTail=sprintf([ ...
    'th=stick(4);if th>-.2 && th<.2,th=single(0);end\n' ...
    'Alt=min(max(single(double(Alt)+double(th)*.001),single(.05)),single(1.8));\n' ...
    'if rangeFlag>RangeOld || rangeFlag==20,Base=Base-single(.02);RangeOld=rangeFlag;end\n' ...
    'raw=single(double(Base)*3.7);']);
autoHead='ControlMode=uint8(stick(5));AltFlag=true;';
actions={ ...
    '', ...
    'Base=single(0);Alt=single(.5);Counter=uint16(0);landingActive=false;AltFlag=false;', ...
    sprintf(['ControlMode=uint8(stick(5));manual=true;th=min(max(stick(4),single(0)),single(1));\n' ...
    'if th>-.2 && th<.2,th=single(0);end\n' ...
    'raw=single((.00413+double(single(3.3)*th-single(5.44)*th*th+single(3.13)*th*th*th))*3.7);']), ...
    [autoHead newline 'Base=min(single(Counter)/single(1000),' trim38 ');Counter=Counter+uint16(1);' newline autoTail], ...
    [autoHead newline 'Base=min(single(Counter)/single(1000),' trimV ');Counter=Counter+uint16(1);' newline autoTail], ...
    [autoHead newline 'Base=' trimV ';' newline autoTail], ...
    sprintf(['AltFlag=false;\nif ~landingActive,landingActive=true;History(:)=height;Base=%s;end\n' ...
    'if History(10)>=height,Base=single(double(Base)*.9999);end\n' ...
    'if height<.15,Base=single(double(Base)*.999);end\n' ...
    'if height<.1,landingActive=false;end\n' ...
    'for j=2:10,History(j)=History(j-1);end\nHistory(1)=height;'],trimV)};
ops={};
for k=1:numel(names)
    label=names{k};if ~isempty(actions{k}),label=[label newline 'en: ' actions{k}];end
    ops{end+1}=reorg.add('State',names{k},names{k},struct('LabelString',label, ...
        'Position',[90+mod(k-1,3)*475 100+floor((k-1)/3)*350 395 280]));
end
ops{end+1}=reorg.add('Junction','CommandSelection','selection',struct('Position',[540 460 12 12]));
ops{end+1}=reorg.transition('?','#Hold', ...
    '/Alt=single(.5);Base=single(0);Counter=uint16(0);RangeOld=uint8(0);landingActive=false;History=zeros(10,1,''single'');AltFlag=false;ControlMode=uint8(0);th=single(0);j=double(0);',1);
reply=reorg.edit(model,phases,ops,'full');ids=struct;
for k=1:numel(names),ids.(names{k})=reorg.created(reply,names{k});end
selection=reorg.created(reply,'selection');
active='(mode==2 || (mode==6 && phase==0 && ~flipDone))';
ops={reorg.transition(phases,selection,'step',1), ...
    reorg.transition(selection,ids.Parking,'[mode==3]',1), ...
    reorg.transition(selection,ids.Landing,'[mode==5]',2), ...
    reorg.transition(selection,ids.ManualAltitude,['[' active ' && uint8(stick(6))~=4]'],3), ...
    reorg.transition(selection,ids.TakeoffReference,['[' active ' && uint8(stick(6))==4 && Counter<500]'],4), ...
    reorg.transition(selection,ids.TakeoffBattery,['[' active ' && uint8(stick(6))==4 && Counter<1000]'],5), ...
    reorg.transition(selection,ids.AutoHover,['[' active ' && uint8(stick(6))==4]'],6), ...
    reorg.transition(selection,ids.Hold,'',7)};
reorg.edit(model,id,ops);
code=sprintf('raw=single(0);manual=false;\nsend(step,CommandPhases);\nalt=Alt;base=Base;counter=Counter;auto=AltFlag;controlMode=single(ControlMode);');
parentPosition=sfroot().find('-isa','Stateflow.Chart','Path',reorg.path(model,id)).find('-isa','Stateflow.State','Name','CommandPhases').Position;
cyclePosition=[parentPosition(1)+parentPosition(3)+2000 parentPosition(2) 650 230];
ops={reorg.add('State','CycleOutputs','cycle',struct('LabelString',['CycleOutputs' newline 'en: ' code newline 'du: ' code], ...
    'ExecutionOrder',2,'Position',cyclePosition)), ...
    reorg.add('Annotation','JapaneseExplanation','note',struct('Text',description,'Position',[50 1250 1650 170]))};
reorg.edit(model,id,ops);
report=struct('StateNames',{names},'NoMATLABFunctions',true);save_system(model);
end
