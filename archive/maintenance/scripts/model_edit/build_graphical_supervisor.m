function result=build_graphical_supervisor()
%BUILD_GRAPHICAL_SUPERVISOR True flight-mode states with native transitions.
% 状態同期→今回の判断の順をローカルイベントで明示し、公式の周期内順序を維持。
model='StampFly_Official_FlightTest400';id='blk_530';
description=sprintf(['飛行モードの状態遷移図（400 Hz）\n' ...
    'INIT→AVERAGE→PARKING→FLIGHT→LANDING。通信途絶・OverG・ボタンを遷移条件で判断。\n' ...
    'CycleInputsが1周期分の入力を整理し、syncで前周期の確定状態に同期、decideで今回の遷移を実行。\n' ...
    'branchは今回の分岐開始状態、modeは今回の判断後の状態。MATLAB関数はChart内に置かない。']);
reorg.chartInterface(model,id,description);
operations={reorg.data('calibration','uint16','0'),reorg.data('buttonCounter','int8','0'), ...
    reorg.data('buttonState','uint8','0'),reorg.data('chatter','uint8','0'), ...
    reorg.data('lastAHRS','uint8','0'),reorg.data('connectionCounter','uint16','0'), ...
    reorg.data('buttonEvent','boolean','false'),reorg.data('calibrationDone','boolean','false'), ...
    reorg.add('Event','sync','sync',struct('Name','sync','Scope','Local')), ...
    reorg.add('Event','decide','decide',struct('Name','decide','Scope','Local')), ...
    reorg.add('State','FlightModes','modes',struct('LabelString','FlightModes','ExecutionOrder',1,'Decomposition','EXCLUSIVE_OR','Position',[60 70 1100 700]))};
reply=reorg.edit(model,id,operations,'full');modes=reorg.created(reply,'modes');
states={'INIT','AVERAGE','PARKING','FLIGHT','LANDING','FLIP','OTHER'};
values=[0 1 3 2 5 6 -1];positions={[70 95 160 70],[290 95 185 80],[560 95 190 80],[810 280 180 90],[550 510 190 80],[820 510 180 80],[85 510 180 70]};
operations={};
for k=1:numel(states)
    action=sprintf('mode=uint8(%d);',values(k));if values(k)<0,action='mode=branch;';end
    operations{end+1}=reorg.add('State',states{k},states{k},struct('LabelString',[states{k} newline 'en: ' action],'Position',positions{k}));
end
operations{end+1}=reorg.add('Junction','InputMode','dispatch',struct('Position',[400 355 12 12]));
operations{end+1}=reorg.transition('?','#INIT', ...
    ['/calibration=uint16(0); buttonCounter=int8(0); buttonState=uint8(0); ' ...
     'chatter=uint8(0); lastAHRS=uint8(0); connectionCounter=uint16(0); ' ...
     'buttonEvent=false; calibrationDone=false;'],1);
reply=reorg.edit(model,modes,operations,'full');
ids=struct;for k=1:numel(states),ids.(states{k})=reorg.created(reply,states{k});end
dispatch=reorg.created(reply,'dispatch');
operations={reorg.transition(modes,dispatch,'sync',1)};
for k=1:numel(states)
    label=sprintf('[branch==uint8(%d)]',values(k));if values(k)<0,label='';end
    operations{end+1}=reorg.transition(dispatch,ids.(states{k}),label,k);
end
operations=[operations,{ ...
    reorg.transition(ids.INIT,ids.AVERAGE,'decide',1), ...
    reorg.transition(ids.AVERAGE,ids.PARKING,'decide[calibrationDone]',1), ...
    reorg.transition(ids.PARKING,ids.FLIGHT,'decide[buttonEvent]/ahrsReset=true;',1), ...
    reorg.transition(ids.FLIGHT,ids.PARKING,'decide[flags(1)==1]/ahrsReset=true;',1), ...
    reorg.transition(ids.FLIGHT,ids.LANDING,'decide[buttonEvent || connected==0]/ahrsReset=true;',2), ...
    reorg.transition(ids.FLIP,ids.PARKING,'decide[flags(1)==1]',1), ...
    reorg.transition(ids.FLIP,ids.LANDING,'decide[buttonEvent || connected==0]',2), ...
    reorg.transition(ids.LANDING,ids.PARKING,'decide[buttonEvent]',1)}];
reorg.edit(model,id,operations);
code=sprintf([ ...
    'branch=previousMode; mode=branch; ahrsReset=false; parkingReset=branch==3;\n' ...
    'buttonEvent=false; calibrationDone=false;\n' ...
    'if newPacket~=0, connectionCounter=uint16(0); end\n' ...
    'connected=uint8(connectionCounter<uint16(40));\n' ...
    'if branch==1\n' ...
    ' calibrationDone=calibration>=uint16(800);\n' ...
    ' if ~calibrationDone, calibration=calibration+uint16(1); end\n' ...
    'elseif branch~=0\n' ...
    ' if button==1\n' ...
    '  buttonCounter=buttonCounter+int8(1);\n' ...
    '  if buttonCounter>int8(10),buttonCounter=int8(10);buttonState=uint8(1);end\n' ...
    ' else\n' ...
    '  buttonCounter=buttonCounter-int8(1);\n' ...
    '  if buttonCounter<int8(-10),buttonCounter=int8(-10);buttonState=uint8(0);end\n' ...
    ' end\n' ...
    ' if chatter==0\n' ...
    '  if buttonState==1,chatter=uint8(1);end\n' ...
    ' elseif buttonState==0\n' ...
    '  chatter=chatter+uint8(1);\n' ...
    '  if chatter>uint8(40),chatter=uint8(0);buttonEvent=true;end\n' ...
    ' end\n' ...
    ' if branch==3\n' ...
    '  if ahrsFlag~=lastAHRS\n' ...
    '   if ahrsFlag==1,ahrsReset=true;end\n' ...
    '   lastAHRS=ahrsFlag;\n' ...
    '  end\n' ...
    ' elseif branch==2 || branch==6\n' ...
    '  connectionCounter=uint16(mod(double(connectionCounter)+1,65536));\n' ...
    '  connected=uint8(connectionCounter<uint16(40));\n' ...
    ' end\n' ...
    'end\n' ...
    'send(sync,FlightModes);\n' ...
    'send(decide,FlightModes);']);
label=['CycleInputs' newline 'en: ' code newline 'du: ' code];
operations={reorg.add('State','CycleInputs','cycle',struct('LabelString',label,'ExecutionOrder',2, ...
    'Position',[1220 70 700 930])),reorg.add('Annotation','JapaneseExplanation','note', ...
    struct('Text',description,'Position',[60 1030 1600 150]))};
reorg.edit(model,id,operations);
result=struct('SID',530,'StateNames',{states},'Description',description,'NoMATLABFunctions',true);
save_system(model);
open_system(reorg.path(model,id));
end
