function align_control_bus_names400()
%ALIGN_CONTROL_BUS_NAMES400 Match virtual bus fields to shared source names.
% 分岐元は同じ信号名を共有するため、各バスの選択名を統一する。
% 演算・順序・状態・データ型を変更しない、再実行可能な修正。
m='StampFly_Official_FlightTest400';
updates={ ...
    'blk_2297','blk_3787','Angles,AngularRate,Altitude,Velocity'; ...
    'blk_3312','blk_3413','Altitude,Velocity'; ...
    'blk_3312','blk_3414','HeightReference,BaseThrust,AltitudeEnabled,ManualAltitude'; ...
    'blk_3674','blk_3739','Run,Reset,OverG,Branch,Dt,FlipDone'; ...
    'blk_3744','blk_3753','VelocityReference,Thrust,Angles,RateReference'; ...
    'blk_3758','blk_3767','RawThrust,ManualAltitude,AltitudeEnabled,ControlMode'};
for k=1:size(updates,1)
    model_read(m,updates{k,1},'0');
    reorg.edit(m,updates{k,1},{reorg.configure(updates{k,2}, ...
        struct('OutputSignals',updates{k,3}))});
end
model_read(m,'blk_2297','0');
reorg.edit(m,'blk_2297',{reorg.configure('blk_3758.y1 -> blk_3419.u1', ...
    struct('Name','ThrustRequest'))});
model_read(m,'blk_3794','0');
memoryNames={'blk_3803','AltitudeEnabled';'blk_3802','AttitudeReset'; ...
    'blk_3809','ParkingReset';'blk_3807','FlipPhase'};
ops={};
for k=1:size(memoryNames,1)
    port=find(strcmp(memoryNames{k,1},{'blk_3803','blk_3802','blk_3809','blk_3807'}))+1;
    ops{end+1}=reorg.configure(sprintf('%s.y1 -> blk_3806.u%d',memoryNames{k,1},port), ...
        struct('Name',memoryNames{k,2})); %#ok<AGROW>
end
reorg.edit(m,'blk_3794',ops);
save_system(m,fullfile(stampfly_project_root(),[m '.slx']));
fprintf('CONTROL_BUS_NAMES_ALIGNED\n');
end
