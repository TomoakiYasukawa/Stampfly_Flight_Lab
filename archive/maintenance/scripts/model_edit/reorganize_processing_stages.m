function stages=reorganize_processing_stages()
%REORGANIZE_PROCESSING_STAGES Separate correction, estimation and control.
% 保持値/リセットの遅延は従来と同じ。主経路はBusを直接配線する。
root=stampfly_project_root();model='StampFly_Official_FlightTest400';
sensorScope='blk_72';flightScope='blk_38';
sensorSelected=ids([1224 1238 1239 1466 1498 572:578 581:583 570 571]);
correctionInputs=[ ...
    reorg.group('IMU',{'blk_75.y1','blk_76.y1'},{'Acceleration','AngularRate'}), ...
    reorg.group('BottomRange',{'blk_77.y1','blk_78.y1'},{'DistanceMm','Fresh'}), ...
    reorg.group('EstimatorContext',{'blk_80.y1','blk_82.y1'},{'PreviousMode','Dt'})];
correctionOutputs=[ ...
    reorg.group('FilteredIMU',{'blk_570.y1','blk_571.y1','blk_578.y1'},{'Acceleration','AngularRate','VerticalDelta'}), ...
    reorg.group('HeightInputs',{'blk_581.y1','blk_582.y1','blk_583.y1'},{'VerticalAcceleration','FilteredRange','RawRange'}), ...
    reorg.group('Calibration',{'blk_574.y1','blk_575.y1'},{'Offsets','Samples'})];
stages.Correction=reorg.groupCopy(model,sensorScope,flightScope,sensorSelected,'SensorCorrection400',correctionInputs,correctionOutputs);
estimationSelected=ids([1465 1499 1500 1501 579 580 584:588]);
estimationInputs=[ ...
    reorg.group('FilteredIMU',{'blk_570.y1','blk_571.y1','blk_578.y1'},{'Acceleration','AngularRate','VerticalDelta'}), ...
    reorg.group('HeightInputs',{'blk_581.y1','blk_582.y1','blk_583.y1'},{'VerticalAcceleration','FilteredRange','RawRange'}), ...
    reorg.group('Calibration',{'blk_574.y1','blk_575.y1'},{'Offsets','Samples'}), ...
    reorg.group('EstimatorContext',{'blk_80.y1','blk_81.y1','blk_82.y1','blk_83.y1','blk_84.y1','blk_561.y1','blk_79.y1'}, ...
    {'PreviousMode','AltitudeEnabled','Dt','AttitudeReset','ParkingReset','FlipPhase','BatteryVoltage'})];
estimationOutputs=[ ...
    reorg.group('Attitude',{'blk_579.y1','blk_580.y1','blk_571.y1'},{'Angles','Quaternion','AngularRate'}), ...
    reorg.group('VerticalMotion',{'blk_584.y1','blk_585.y1'},{'Altitude','Velocity'}), ...
    reorg.group('SensorStatus',{'blk_587.y1','blk_588.y1'},{'Flags','Diagnostics'})];
% AngularRate is passed through the estimation subsystem unchanged.
estimationSelected=[estimationSelected,{'blk_86'}];
% Use a pass-through signal spec rather than copying an output terminal.
reply=reorg.edit(model,sensorScope,{reorg.add('SignalSpecification','EstimatedAngularRate','ratePass', ...
    struct('OutDataTypeStr','single','Dimensions','3'))});
ratePass=reorg.created(reply,'ratePass');reorg.edit(model,sensorScope,{reorg.wire('blk_571.y1',[ratePass '.u1'])});
estimationSelected(end)={ratePass};
estimationOutputs(1).Members(3).Endpoint=[ratePass '.y1'];
stages.Estimation=reorg.groupCopy(model,sensorScope,flightScope,estimationSelected,'AttitudeAltitudeEstimation400',estimationInputs,estimationOutputs);
% Reconnect the original flight supervisor/controller to the new stage outputs.
correctionFields=reorg.outputMap(model,flightScope,stages.Correction.ID,correctionOutputs);
estimateFields=reorg.outputMap(model,flightScope,stages.Estimation.ID,estimationOutputs);
ops={ ...
    reorg.add('BusCreator','RawIMU','imuBus',struct('Inputs','2')), ...
    reorg.add('BusCreator','BottomRange','rangeBus',struct('Inputs','2')), ...
    reorg.add('BusCreator','CorrectionContext','correctionContext',struct('Inputs','2')), ...
    reorg.add('BusCreator','EstimatorContext','estimatorContext',struct('Inputs','7')), ...
    reorg.wire('blk_41.y1','#imuBus.u1','Acceleration'),reorg.wire('blk_42.y1','#imuBus.u2','AngularRate'), ...
    reorg.wire('blk_43.y1','#rangeBus.u1','DistanceMm'),reorg.wire('blk_44.y1','#rangeBus.u2','Fresh'), ...
    reorg.wire('blk_66.y1','#correctionContext.u1','PreviousMode'),reorg.wire('blk_50.y1','#correctionContext.u2','Dt'), ...
    reorg.wire('#imuBus.y1',[stages.Correction.ID '.u1'],'RawIMU'), ...
    reorg.wire('#rangeBus.y1',[stages.Correction.ID '.u2'],'BottomRange'), ...
    reorg.wire('#correctionContext.y1',[stages.Correction.ID '.u3'],'CorrectionContext'), ...
    reorg.wire([stages.Correction.ID '.y1'],[stages.Estimation.ID '.u1'],'FilteredIMU'), ...
    reorg.wire([stages.Correction.ID '.y2'],[stages.Estimation.ID '.u2'],'HeightInputs'), ...
    reorg.wire([stages.Correction.ID '.y3'],[stages.Estimation.ID '.u3'],'Calibration'), ...
    reorg.wire('blk_66.y1','#estimatorContext.u1','PreviousMode'), ...
    reorg.wire('blk_69.y1','#estimatorContext.u2','AltitudeEnabled'), ...
    reorg.wire('blk_50.y1','#estimatorContext.u3','Dt'), ...
    reorg.wire('blk_67.y1','#estimatorContext.u4','AttitudeReset'), ...
    reorg.wire('blk_68.y1','#estimatorContext.u5','ParkingReset'), ...
    reorg.wire('blk_534.y1','#estimatorContext.u6','FlipPhase'), ...
    reorg.wire('blk_45.y1','#estimatorContext.u7','BatteryVoltage'), ...
    reorg.wire('#estimatorContext.y1',[stages.Estimation.ID '.u4'],'EstimatorContext')};
oldOutputs={'blk_85','blk_86','blk_87','blk_88','blk_89','blk_90','blk_91'};
newEndpoints={estimateFields.Angles,estimateFields.AngularRate,estimateFields.Altitude,estimateFields.Velocity, ...
    estimateFields.Flags,estimateFields.Quaternion,estimateFields.Diagnostics};
sensorPath=reorg.path(model,sensorScope);ports=get_param(sensorPath,'PortHandles');
for k=1:numel(oldOutputs)
    line=get_param(ports.Outport(k),'Line');dest=get_param(line,'DstPortHandle');
    for d=dest'
        ops{end+1}=reorg.wire(newEndpoints{k},sprintf('%s.u%d',reorg.id(get_param(d,'Parent')),get_param(d,'PortNumber')));
    end
end
ops{end+1}=struct('op','delete','target',sensorScope);
reorg.edit(model,flightScope,ops);
% Capture remaining control blocks; stage output selectors remain outside.
flightPath=reorg.path(model,flightScope);blocks=find_system(flightPath,'SearchDepth',1,'Type','Block');
excluded={stages.Correction.ID,stages.Estimation.ID};
selected={};
for k=1:numel(blocks)
    if strcmp(blocks{k},flightPath),continue;end
    type=get_param(blocks{k},'BlockType');id=reorg.id(blocks{k});
    if ismember(id,excluded) || ismember(type,{'Inport','Outport','BusCreator','BusSelector'}) || ...
            ismember(get_param(blocks{k},'Name'),{'ModelExplanation','FlipNormalDiagnostic'}),continue;end
    selected{end+1}=id;
end
% FlipNormalDiagnostic terminates the normalControl signal inside the group.
selected{end+1}='blk_562';
controlInputs=[ ...
    reorg.group('Attitude', {estimateFields.Angles,estimateFields.AngularRate},{'Angles','AngularRate'}), ...
    reorg.group('VerticalMotion',{estimateFields.Altitude,estimateFields.Velocity},{'Altitude','Velocity'}), ...
    reorg.group('FlightInputs',{'blk_46.y1','blk_47.y1','blk_48.y1','blk_49.y1','blk_529.y1','blk_45.y1','blk_50.y1',estimateFields.Flags}, ...
    {'Sticks','ArmButton','NewPacket','AHRSRequest','FlipButton','BatteryVoltage','Dt','Flags'})];
controlOutputs=[ ...
    reorg.group('MotorCommand',{'blk_92.y1','blk_92.y2'},{'Duty','Counts'}), ...
    reorg.group('FlightStatus',{'blk_92.y8','blk_66.y1','blk_589.y1','blk_530.y5','blk_92.y5','blk_92.y3'}, ...
    {'Mode','PreviousMode','AltitudeEnabled','Connected','FlipPhase','Diagnostics'}), ...
    reorg.group('EstimatorFeedback',{'blk_66.y1','blk_69.y1','blk_67.y1','blk_68.y1','blk_534.y1'}, ...
    {'PreviousMode','AltitudeEnabled','AttitudeReset','ParkingReset','FlipPhase'})];
stages.Control=reorg.groupCopy(model,flightScope,flightScope,selected,'FlightControl400',controlInputs,controlOutputs);
stages.CorrectionFields=correctionFields;stages.EstimationFields=estimateFields;
stages.ControlInputs=controlInputs;stages.ControlOutputs=controlOutputs;
save(fullfile(root,'tests','processing_stage_ids.mat'),'stages');
save_system(model);
end
function result=ids(values)
result=arrayfun(@(v)['blk_' num2str(v)],values,'UniformOutput',false);
end
