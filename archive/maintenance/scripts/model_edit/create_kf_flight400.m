function report=create_kf_flight400(stage)
%CREATE_KF_FLIGHT400 Copy the flown IMU model and standardize altitude Kalman.
% Use SATK model_edit for scoped structure and parameter changes.
if nargin==0,stage='all';end
root=stampfly_project_root();ensure_simulink_toolkit();
gate=library.settingsLookup();assert(gate.gatePass);
% Suppress only this batch session's automatic listeners while configuring a
% linked filter. Explicit model_edit layouts still arrange each edited scope.
model='StampFly_KF400';source='StampFly_IMU400';
layoutListeners=layout.LayoutListeners();
layoutDisabler=layoutListeners.getScopedLayoutListenerDisabler(model); %#ok<NASGU>
if strcmp(stage,'all')
    create_kf_flight400('copy');report=create_kf_flight400('replace');return
end
if strcmp(stage,'copy')
    assert(~isfile(stampfly_model_file(model)),'kf400:Exists','KF model already exists.');
    open_system(fullfile(root,[source '.slx']));
    assert(strcmp(get_param(source,'Dirty'),'off'),'kf400:UnsavedSource','Source must be saved before copying.');
    copyfile(fullfile(root,[source '.slx']),stampfly_model_file(model));
    open_system(stampfly_model_file(model));
    reorg.edit(model,'root',{reorg.configure(['config:' model],struct( ...
        'InitFcn','init_kf_flight;', ...
        'PostLoadFcn',sprintf("run(fullfile(fileparts(get_param('%s','FileName')),'config','startup.m'));",model), ...
        'Description','StampFly 400 Hz: standard IMU Filter and standard altitude Kalman Filter; original flight control retained.'))},'incremental');
    init_kf_flight();save_system(model);report=struct('Model',model,'Stage','copy');
    fprintf('KF400_COPY_SAVED\n');return
end
assert(strcmp(stage,'replace'));
open_system(stampfly_model_file(model));init_kf_flight();
scope='blk_2231';old='blk_2236';disp(model_read(model,scope,'0'));
links=reorg.links(model,scope);oldPath=reorg.path(model,old);
oldName=get_param(oldPath,'Name');
assert(strcmp(get_param(oldPath,'SFBlockType'),'MATLAB Function'));
unfinished=find_system(reorg.path(model,scope),'SearchDepth',1,'Name','AltitudeKalman400');
if ~isempty(unfinished)
    assert(isscalar(unfinished));
    reorg.edit(model,scope,{struct('op','delete','target',reorg.id(unfinished{1}))},'incremental');
end
load_system('simulink');load_system('ctrlSharedLib');
enableLibrary=Simulink.ID.getFullName('simulink:144:13');
reply=reorg.edit(model,scope,{struct('op','create_subsystem','name','AltitudeKalman400','ref','altitude', ...
    'interface',struct('inputs',{{'AltitudeM','AccelerationG','PreviousMode','Dt','ParkingReset'}}, ...
    'outputs',{{'HeightM','VelocityMps','EstimatedBias'}}))},'incremental');
altitude=reorg.created(reply,'altitude');[ip,op]=reorg.ports(model,altitude);
reply=reorg.edit(model,altitude,{reorg.add('MATLAB Function','UpdateSchedule','schedule'), ...
    reorg.add('Constant','ProcessParameters','parameters',struct('Value','AltitudeKF.ProcessParameters')), ...
    struct('op','create_subsystem','name','FilterStep','ref','step', ...
    'interface',struct('inputs',{{'AltitudeM','AccelerationG','Dt','A','B','C','Q','Reset','ProcessParameters'}}, ...
    'outputs',{{'StateVector'}})), ...
    reorg.add('MATLAB Function','FlightOutputs','outputs')},'full');
schedule=reorg.created(reply,'schedule');step=reorg.created(reply,'step');
parameters=reorg.created(reply,'parameters');outputs=reorg.created(reply,'outputs');
writeFunction(root,model,schedule,'KF400Schedule.m');
writeFunction(root,model,outputs,'KF400FlightOutputs.m');
[si,so]=reorg.ports(model,step);
filterParameters=struct('TimeDomain','Discrete-Time','UseCurrentEstimator','on', ...
    'ModelSource','Input port','NumberOfStates','3','NumberOfInputs','1','NumberOfOutputs','1', ...
    'Ts','AltitudeKF.SampleTime','TimeInvariantQ','off','R','AltitudeKF.MeasurementVariance', ...
    'TimeInvariantR','on','N','zeros(3,1,''single'')','TimeInvariantN','on', ...
    'UseGH','off','InitialEstimateSource','Input port','ExternalReset','Level hold', ...
    'AddInputPort','on','AddEnablePort','off','OutputP','off','OutputEstimatedY','off');
reply=reorg.edit(model,step,{reorg.add(enableLibrary,'Enable','enable',struct('StatesWhenEnabling','held')), ...
    reorg.configure(step,struct('TreatAsAtomicUnit','on')), ...
    reorg.add('ctrlSharedLib/Kalman Filter','KalmanFilter','filter',filterParameters), ...
    reorg.add('MATLAB Function','AdvanceCorrectedState','current'), ...
    reorg.add('UnitDelay','RetainedPrivateState','state', ...
    struct('InitialCondition','AltitudeKF.InitialState','SampleTime','-1')), ...
    reorg.add('Constant','InitialCovariance','p0',struct('Value','AltitudeKF.InitialCovariance','VectorParams1D','off')), ...
    reorg.add('Constant','ZeroFeedthrough','d',struct('Value','single(0)')), ...
    reorg.configure(so{1},struct('InitialOutput','AltitudeKF.InitialState','OutputWhenDisabled','held'))},'full');
filter=reorg.created(reply,'filter');current=reorg.created(reply,'current');
state=reorg.created(reply,'state');p0=reorg.created(reply,'p0');d=reorg.created(reply,'d');
writeFunction(root,model,current,'KF400CurrentState.m');
ki=find_system(reorg.path(model,filter),'SearchDepth',1,'FollowLinks','on','LookUnderMasks','all','BlockType','Inport');
[~,order]=sort(cellfun(@(p)str2double(get_param(p,'Port')),ki));ki=ki(order);
portNames=cellfun(@(p)get_param(p,'Name'),ki,'UniformOutput',false);disp(portNames);
% Resolve optional standard-block ports from the actual mask-created Inports.
names={'u','y','A','B','C','D','Q','X0','P0','Reset'};
feeds={[si{2} '.y1'],[si{1} '.y1'],[si{4} '.y1'],[si{5} '.y1'],[si{6} '.y1'], ...
    [d '.y1'],[si{7} '.y1'],[state '.y1'],[p0 '.y1'],[si{8} '.y1']};
ops={};
for k=1:numel(names)
    port=find(strcmpi(portNames,names{k}));assert(isscalar(port),'kf400:Port','Missing %s',names{k});
    ops{end+1}=reorg.wire(feeds{k},sprintf('%s.u%d',filter,port)); %#ok<AGROW>
end
ops=[ops {reorg.wire([filter '.y1'],[current '.u1']), ...
    reorg.wire([si{2} '.y1'],[current '.u2']),reorg.wire([si{3} '.y1'],[current '.u3']), ...
    reorg.wire([si{9} '.y1'],[current '.u4']), ...
    reorg.wire([current '.y1'],[state '.u1']),reorg.wire([current '.y1'],[so{1} '.u1'])}];
reorg.edit(model,step,ops,'full');
ops={reorg.wire([ip{3} '.y1'],[schedule '.u1']),reorg.wire([ip{4} '.y1'],[schedule '.u2']), ...
    reorg.wire([ip{5} '.y1'],[schedule '.u3']),reorg.wire([parameters '.y1'],[schedule '.u4']), ...
    reorg.wire([ip{1} '.y1'],[step '.u1']),reorg.wire([ip{2} '.y1'],[step '.u2']), ...
    reorg.wire([ip{4} '.y1'],[step '.u3']),reorg.wire([schedule '.y3'],[step '.u4'],'StateMatrix'), ...
    reorg.wire([schedule '.y4'],[step '.u5'],'InputMatrix'), ...
    reorg.wire([schedule '.y5'],[step '.u6'],'ObservationMatrix'), ...
    reorg.wire([schedule '.y6'],[step '.u7'],'ProcessCovariance'), ...
    reorg.wire([schedule '.y2'],[step '.u8'],'CovarianceReset'), ...
    reorg.wire([parameters '.y1'],[step '.u9']),reorg.wire([schedule '.y1'],[step '.Enable'],'Run'), ...
    reorg.wire([step '.y1'],[outputs '.u1']),reorg.wire([schedule '.y1'],[outputs '.u2']), ...
    reorg.wire([ip{5} '.y1'],[outputs '.u3'])};
for k=1:3,ops{end+1}=reorg.wire(sprintf('%s.y%d',outputs,k),[op{k} '.u1']);end %#ok<AGROW>
reorg.edit(model,altitude,ops,'full');
% Connect the complete replacement using the saved original endpoints.
ops={};
for k=1:numel(links)
    l=links(k);
    if strcmp(l.Dst,old)
        ops{end+1}=reorg.wire(sprintf('%s.y%d',l.Src,l.SrcPort),sprintf('%s.u%d',altitude,l.DstPort),l.Name); %#ok<AGROW>
    elseif strcmp(l.Src,old)
        ops{end+1}=reorg.wire(sprintf('%s.y%d',altitude,l.SrcPort),sprintf('%s.u%d',l.Dst,l.DstPort),l.Name); %#ok<AGROW>
    end
end
reorg.edit(model,scope,ops,'incremental');
reorg.edit(model,scope,{struct('op','delete','target',old), ...
    reorg.configure(altitude,struct('Name',oldName,'TreatAsAtomicUnit','on', ...
    'Description','Standard time-varying altitude Kalman Filter. State [velocity;height;bias]. Current dt/az timing, original mode hold and private-state-retaining parking reset are preserved.'))},'incremental');
% Identify this firmware separately while retaining the wire protocol.
logger=find_system(model,'LookUnderMasks','all','BlockType','MATLABSystem','System','basic.ExtendedLogger50');
assert(isscalar(logger));reorg.edit(model,reorg.id(get_param(logger{1},'Parent')), ...
    {reorg.configure(reorg.id(logger{1}),struct('FirmwareRevision','uint32(1801)'))},'incremental');
note=sprintf('姿勢・高度推定 / 400 Hz\nIMU Filterで姿勢・補正済み角速度、標準Kalman Filterで高度・鉛直速度を推定。\n加速度の単位・ToF前処理・PIDは飛行成功IMU版と共通。');
reorg.edit(model,scope,{reorg.configure('blk_3297',struct('Description',note, ...
    'MaskDisplay',sprintf("disp(sprintf('%s'));",strrep(note,newline,'\n'))))},'incremental');
for group={step,altitude,scope,'root'}
    check=char(model_check(model,group{1},'["all"]'));disp(check);
    assert(~contains(check,'severity: error'),'kf400:Connectivity','Incomplete scope %s',group{1});
end
save_system(model);
report=struct('Model',model,'SourceModel',source,'AltitudeBlock',altitude, ...
    'FilterStepBlock',step,'FilterBlock',filter,'ScheduleBlock',schedule, ...
    'CurrentStateBlock',current,'PrivateStateBlock',state,'OutputBlock',outputs, ...
    'StandardFilterReference','ctrlSharedLib/Kalman Filter', ...
    'SourceModelSHA256',sha256(fullfile(root,[source '.slx'])), ...
    'ModelSHA256',sha256(stampfly_model_file(model)), ...
    'SampleTime',0.0025,'FirmwareRevision',1801,'RadioChannel',3,'Flashed',false);
fid=fopen(fullfile(root,'docs','history','kf_flight_structure.json'),'w','n','UTF-8');assert(fid>=0);
fprintf(fid,'%s\n',jsonencode(report,'PrettyPrint',true));fclose(fid);
fprintf('KF400_REPLACEMENT_SAVED\n');
end
function writeFunction(root,model,id,file)
disp(model_read(model,id,'0'));
config=get_param(reorg.path(model,id),'MATLABFunctionConfiguration');
config.FunctionScript=fileread(fullfile(root,'code','model_algorithms',file));
assert(strcmp(config.FunctionScript,fileread(fullfile(root,'code','model_algorithms',file))));
disp(model_read(model,id,'0'));
end
function digest=sha256(file)
[status,value]=system(sprintf('powershell -NoProfile -Command "(Get-FileHash -LiteralPath ''%s'' -Algorithm SHA256).Hash"',strrep(file,'''','''''')));
assert(status==0);digest=lower(strtrim(value));
end
