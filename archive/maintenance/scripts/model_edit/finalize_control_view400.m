function params = caption(title,inputs,outputs,description)
icon = ['disp(''' title '\nダブルクリックで内部を編集'');'];
for k=1:numel(inputs)
    icon = [icon sprintf('port_label(''input'',%d,''%s'');',k,inputs{k})]; %#ok<AGROW>
end
for k=1:numel(outputs)
    icon = [icon sprintf('port_label(''output'',%d,''%s'');',k,outputs{k})]; %#ok<AGROW>
end
params = struct('Mask','on','MaskDisplay',char(icon),'MaskIconOpaque','opaque', ...
    'MaskIconFrame','on','ShowPortLabels','none','FontSize','12', ...
    'ShowName','on','AttributesFormatString','','Description',description);
end

function params = noteDisplay(lines)
description = strjoin(lines,newline);
icon = ['disp(''' char(strrep(description,newline,'\n')) ''')'];
params = struct('MaskDisplay',icon,'MaskIconFrame','off','ShowName','off', ...
    'FontSize','14','Description',description);
end

function hideBusNames(m,scope)
p = reorg.path(m,scope);
blocks = find_system(p,'SearchDepth',1,'Type','Block'); ops = {};
for k=1:numel(blocks)
    if ismember(get_param(blocks{k},'BlockType'),{'BusCreator','BusSelector'})
        ops{end+1} = reorg.configure(reorg.id(blocks{k}),struct('ShowName','off','FontSize','10','AttributesFormatString','')); %#ok<AGROW>
    end
end
if ~isempty(ops),reorg.edit(m,scope,ops);end
end

function place(m,items)
for k=1:size(items,1),set_param(reorg.path(m,items{k,1}),'Position',items{k,2});end
end

function route(m,scope)
lines = find_system(reorg.path(m,scope),'SearchDepth',1,'FindAll','on','Type','line');
if ~isempty(lines),Simulink.BlockDiagram.routeLine(lines);end
end

function singleRoute(m,id,port,waypoints)
h=get_param(reorg.path(m,id),'PortHandles');line=get_param(h.Outport(port),'Line');
assert(line>0 && isempty(get_param(line,'LineChildren')));
points=get_param(line,'Points');
set_param(line,'Points',[points(1,:);waypoints;points(end,:)]);
end

function rail(m,id,port,y)
h=get_param(reorg.path(m,id),'PortHandles');line=get_param(h.Outport(port),'Line');
points=get_param(line,'Points');railNode(line,points(1,:),y);
end

function railNode(line,start,y)
children=get_param(line,'LineChildren');
if isempty(children)
    points=get_param(line,'Points');finish=points(end,:);
    bend=max(start(1),finish(1)-60);
    points=[start;bend y;bend finish(2);finish];
else
    destinations=get_param(line,'DstPortHandle');destinations=destinations(destinations>0);
    x=arrayfun(@(p)portX(p),destinations);
    joint=[max(start(1)+25,min(x)-50) y];
    points=[start;start(1) y;joint];
end
% Repeated points add no information and can produce invalid line segments.
points=points([true;any(diff(points,1,1)~=0,2)],:);
set_param(line,'Points',points);
if ~isempty(children)
    for k=1:numel(children),railNode(children(k),joint,y);end
end
end

function x=portX(port)
position=get_param(port,'Position');x=position(1);
end
