function place(model,items)
for k=1:size(items,1),set_param(reorg.path(model,items{k,1}),'Position',items{k,2});end
end

function placeTags(scope)
for type={'Goto','From'}
    blocks=find_system(scope,'SearchDepth',1,'BlockType',type{1});
    for k=1:numel(blocks)
        ports=get_param(blocks{k},'PortHandles');width=max(100,9*numel(get_param(blocks{k},'GotoTag')));
        if strcmp(type{1},'Goto')
            line=get_param(ports.Inport,'Line');if line<0,continue;end
            p=get_param(line,'SrcPortHandle');if p<0,continue;end
            q=get_param(p,'Position');pos=[q(1)+30 q(2)-10 q(1)+30+width q(2)+10];
        else
            line=get_param(ports.Outport,'Line');if line<0,continue;end
            ps=get_param(line,'DstPortHandle');ps=ps(ps>0);if isempty(ps),continue;end
            q=get_param(ps(1),'Position');pos=[q(1)-30-width q(2)-10 q(1)-30 q(2)+10];
        end
        set_param(blocks{k},'Position',pos,'ShowName','off','FontSize','10');
    end
end
end

function routeLines(scope)
lines=find_system(scope,'FindAll','on','SearchDepth',1,'Type','Line');
if ~isempty(lines),Simulink.BlockDiagram.routeLine(lines);end
end

function display=maskText(text)
display=char("disp(sprintf('"+strrep(strrep(string(text),"'","''"),newline,'\n')+"')); ");
end
