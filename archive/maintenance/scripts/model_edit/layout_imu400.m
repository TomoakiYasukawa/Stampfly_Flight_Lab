function fitSymbols(scope)
blocks=find_system(scope,'SearchDepth',1,'Type','Block');
for k=1:numel(blocks)
    block=blocks{k};if strcmp(block,scope),continue;end
    type=get_param(block,'BlockType');ports=get_param(block,'PortHandles');
    parameters=get_param(block,'ObjectParameters');
    if isfield(parameters,'ContentPreviewEnabled'),set_param(block,'ContentPreviewEnabled','off');end
    if strcmp(type,'SubSystem')&&~isempty(get_param(block,'MaskType')),continue;end
    if strcmp(type,'SubSystem')&&~isempty(ports.Inport)|| ...
            strcmp(type,'SubSystem')&&~isempty(ports.Outport)
        pos=get_param(block,'Position');
        count=max(numel(ports.Inport),numel(ports.Outport));
        width=max(300,pos(3)-pos(1));height=max(110,38*count+50);
        pos(3:4)=pos(1:2)+[width height];set_param(block,'Position',pos);
    end
    if strcmp(type,'SubSystem')&&isempty(ports.Inport)&&isempty(ports.Outport)&& ...
            ismember(get_param(block,'Name'),{'JapaneseExplanation','ModelExplanation'})
        pos=get_param(block,'Position');
        set_param(block,'Position',[20 10 max(800,pos(3)) 120],'ShowName','off');
    end
end
end

function normalizeDiagram(scope)
% Isolated explanation masks otherwise push an entire diagram far to the right.
blocks=find_system(scope,'SearchDepth',1,'Type','Block');core={};notes={};
for k=1:numel(blocks)
    if strcmp(blocks{k},scope),continue;end
    if ismember(get_param(blocks{k},'Name'),{'JapaneseExplanation','ModelExplanation'})
        notes{end+1}=blocks{k}; %#ok<AGROW>
    else
        core{end+1}=blocks{k}; %#ok<AGROW>
    end
end
if isempty(core),return;end
positionCells=cellfun(@(p)get_param(p,'Position'),core,'UniformOutput',false);
positions=vertcat(positionCells{:});
delta=[40-min(positions(:,1)),180-min(positions(:,2))];
for k=1:numel(core)
    pos=positions(k,:)+[delta delta];set_param(core{k},'Position',pos);
end
right=max(positions(:,3))+delta(1);
for k=1:numel(notes)
    set_param(notes{k},'Position',[40 20 max(900,right) 120], ...
        'ShowName','off','ContentPreviewEnabled','off');
end
end

