function report=compact_control_wiring400()
%COMPACT_CONTROL_WIRING400 Share named buses instead of long scalar fan-ins.
% 演算ブロックは変更せず、既存のバス選択と配線だけをまとめ直す。
m='StampFly_Official_FlightTest400';scope='blk_2297';
assert(strcmp(get_param(m,'SimulationStatus'),'stopped'));
model_read(m,scope,'0');
firstPass=get_param(reorg.path(m,'blk_3418'),'Inputs')=="4";
if firstPass
updates={ ...
    'blk_3312','blk_3415','ThrustRequest,ControlContext.VelocityEnabled,ControlContext.AltitudeEnabled,ControlContext.Reset,ControlContext.FlipPhase,FlightContext.Branch,Mode,Dt,PreviousError'; ...
    'blk_3421','blk_3525','PilotInput.Sticks,SharedControlContext.FlightContext.Branch,SharedControlContext.FlightContext.FlipPhase,SharedControlContext.FlightContext.FlipRate,SharedControlContext.FlightContext.FlipDone,SharedControlContext.ControlMode'; ...
    'blk_3421','blk_3526','ControlContext.Run,ControlContext.Reset,ControlContext.AngleEnabled,ControlContext.AngleReset,FlightContext.FlipAngleReset,Dt'; ...
    'blk_3529','blk_3672','ControlContext.Run,ControlContext.Reset,Dt,PreviousError'; ...
    'blk_3674','blk_3739','ControlContext.Run,ControlContext.Reset,PilotInput.OverG,FlightContext.Branch,Dt,FlightContext.FlipDone'; ...
    'blk_3758','blk_3768','FlightContext.Branch,Dt,FlightContext.FlipPhase,FlightContext.FlipThrust,FlightContext.FlipStart,FlightContext.FlipDone,Mode'};
for k=1:size(updates,1)
    reorg.edit(m,updates{k,1},{reorg.configure(updates{k,2},struct('OutputSignals',updates{k,3}))});
end
ops={reorg.configure('blk_3418',struct('Inputs','7','Name','FlightCommandBus')), ...
    reorg.configure('blk_3527',struct('Inputs','2','Name','AttitudePilotContextBus')), ...
    reorg.configure('blk_3772',struct('Inputs','3','Name','ModeContextBus')), ...
    reorg.add('BusCreator','SharedControlContextBus','common',struct('Inputs','8'))};
commandNames={'HeightReference','BaseThrust','RampCounter','RawThrust','AltitudeEnabled','ManualAltitude','ControlMode'};
for k=1:7,ops{end+1}=reorg.wire(sprintf('blk_2606.y%d',k),sprintf('blk_3418.u%d',k),commandNames{k});end %#ok<AGROW>
commonSources={'blk_3758.y2','blk_2300.y1','blk_2298.y1','blk_2364.y1', ...
    'blk_2301.y1','blk_2705.y1','blk_3758.y1','blk_2606.y7'};
commonNames={'ControlContext','FlightContext','PilotInput','Mode','Dt','PreviousError','ThrustRequest','ControlMode'};
for k=1:8,ops{end+1}=reorg.wire(commonSources{k},sprintf('#common.u%d',k),commonNames{k});end %#ok<AGROW>
ops=[ops,{ ...
    reorg.wire('blk_2299.y1','blk_3312.u1','MeasuredState'), ...
    reorg.wire('blk_3418.y1','blk_3312.u2','FlightCommand'), ...
    reorg.wire('blk_3418.y1','blk_3758.u1','FlightCommand'), ...
    reorg.wire('blk_3418.y1','blk_3744.u1','FlightCommand'), ...
    reorg.wire('#common.y1','blk_3312.u3','SharedControlContext'), ...
    reorg.wire('#common.y1','blk_3421.u3','SharedControlContext'), ...
    reorg.wire('#common.y1','blk_3529.u3','SharedControlContext'), ...
    reorg.wire('#common.y1','blk_3674.u2','SharedControlContext'), ...
    reorg.wire('blk_2298.y1','blk_3527.u1','PilotInput'), ...
    reorg.wire('#common.y1','blk_3527.u2','SharedControlContext'), ...
    reorg.wire('blk_2300.y1','blk_3772.u1','FlightContext'), ...
    reorg.wire('blk_2364.y1','blk_3772.u2','Mode'), ...
    reorg.wire('blk_2301.y1','blk_3772.u3','Dt'), ...
    reorg.wire('blk_3312.y3','blk_3758.u3','ThrustState')}];
obsolete={'blk_3417','blk_3419','blk_3528','blk_3673','blk_3742', ...
    'blk_3755','blk_3771','blk_3773','blk_3420'};
for k=1:numel(obsolete),ops{end+1}=struct('op','delete','target',obsolete{k});end %#ok<AGROW>
reply=reorg.edit(m,scope,ops);
report=struct('SharedContextBus',reorg.created(reply,'common'));
else
report=struct('SharedContextBus','blk_3818');
end
% Retain output vector order while avoiding technical names on wire bundles.
reorg.edit(m,scope,{reorg.configure('blk_3756',struct('Name','ControlReferencesBus')), ...
    reorg.configure('blk_3757',struct('Name','MotorDiagnosticsBus'))});
% Recreate trimmed selectors so deleted scalar branches cannot remain dangling.
oldSelector=reorg.path(m,'blk_3787');
if ishandle(get_param(oldSelector,'Handle'))
    ops={struct('op','delete','target','blk_3787'),struct('op','delete','target','blk_3788'), ...
        struct('op','delete','target','blk_3774'), ...
        reorg.add('BusSelector','MeasuredStateFields','measured',struct('OutputSignals','Angles,AngularRate,Altitude')), ...
        reorg.add('BusSelector','FlightContextFields','flight',struct('OutputSignals','Branch,PreMode,FlipPhase,FlipStart,FlipDone')), ...
        reorg.add('BusSelector','StatusContextFields','status',struct('OutputSignals','Reset,FlipPhase')), ...
        reorg.wire('blk_2299.y1','#measured.u1'),reorg.wire('blk_2300.y1','#flight.u1'), ...
        reorg.wire('blk_3758.y2','#status.u1'), ...
        reorg.wire('#measured.y1','blk_3421.u1'),reorg.wire('#measured.y2','blk_3529.u2'), ...
        reorg.wire('#measured.y3','blk_2364.u3'),reorg.wire('#measured.y3','blk_2606.u2'), ...
        reorg.wire('#flight.y1','blk_2606.u5'),reorg.wire('#flight.y1','blk_2364.u1'), ...
        reorg.wire('#flight.y2','blk_2364.u2'),reorg.wire('#flight.y3','blk_2606.u6'), ...
        reorg.wire('#flight.y4','blk_2364.u4'),reorg.wire('#flight.y5','blk_2364.u5'), ...
        reorg.wire('#flight.y5','blk_2606.u7'),reorg.wire('#status.y1','blk_3789.u4'), ...
        reorg.wire('#status.y2','blk_3789.u3')};
    reply=reorg.edit(m,scope,ops);
    report.MeasuredFields=reorg.created(reply,'measured');
    report.FlightFields=reorg.created(reply,'flight');
    report.StatusFields=reorg.created(reply,'status');
end
check=char(model_check(m,scope,'["all"]'));disp(check);
assert(startsWith(strtrim(check),'status: healthy'));
save(fullfile(stampfly_project_root(),'build','tests','compact_control_ids.mat'),'report');
save_system(m,fullfile(stampfly_project_root(),[m '.slx']));
fprintf('CONTROL_WIRING_COMPACTED\n');
end
