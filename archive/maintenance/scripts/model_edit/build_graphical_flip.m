function report=build_graphical_flip()
%BUILD_GRAPHICAL_FLIP Eight actual phases; all guards/actions are native SF.
model='StampFly_Official_FlightTest400';id='blk_531';
description=sprintf(['Flipの段階を状態遷移図で表示（400 Hz）\n' ...
    'Boost 180周期 → 加速/減速4段階（各40周期）→ 姿勢リセット10周期 → 回復190周期 → 完了。\n' ...
    'stepイベント1回につき1周期分だけ実行。割込み・待機時のカウンター/指令保持も公式と同じ。\n' ...
    '姿勢PIDはChart外。Chart内にMATLAB関数は置かない。']);
reorg.chartInterface(model,id,description);
ops={reorg.data('counter','uint16','0'),reorg.data('buttonCount','uint8','0'), ...
    reorg.data('rate','single','0'),reorg.data('didReset','boolean','false'), ...
    reorg.data('trimThrust','single','0'),reorg.data('domega','single','0'), ...
    reorg.data('quarter','uint16','40'),reorg.data('flipStep','uint16','160'), ...
    reorg.data('restartPhase','boolean','false'), ...
    reorg.add('Event','step','step',struct('Name','step','Scope','Local')), ...
    reorg.add('State','FlipPhases','phases',struct('LabelString','FlipPhases', ...
    'ExecutionOrder',1,'Decomposition','EXCLUSIVE_OR','Position',[40 50 1300 1000]))};
reply=reorg.edit(model,id,ops,'full');phases=reorg.created(reply,'phases');
names={'Idle','Boost','AccelFirst','AccelSecond','DecelFirst','DecelSecond','AttitudeReset','Recovery','Complete'};
actions={ ...
    '', ...
    ['phase=uint8(1);normalControl=false;' newline 'if voltage>3.8,thrust=single(double(trimThrust)+.17*3.7);else,thrust=single(double(trimThrust)+.15*3.7);end'], ...
    'phase=uint8(2);normalControl=false;thrust=trimThrust*single(.3);rate=rate+domega;', ...
    'phase=uint8(3);normalControl=false;thrust=trimThrust*single(.15);rate=rate+domega;', ...
    'phase=uint8(4);normalControl=false;thrust=trimThrust*single(.15);rate=rate-domega;', ...
    'phase=uint8(5);normalControl=false;thrust=trimThrust;rate=rate-domega;', ...
    ['phase=uint8(6);normalControl=false;thrust=single(double(trimThrust)+double(single(.18))*3.7);rate=single(0);angleReset=true;' newline 'if ~didReset,ahrsReset=true;didReset=true;end'], ...
    'normalControl=true;', ...
    'done=true;normalControl=false;counter=uint16(0);didReset=false;'};
ops={};
for k=1:numel(names)
    action=actions{k};
    if k>1
        action=[action newline 'rollRate=rate;'];
        if k<numel(names),action=[action newline 'counter=counter+uint16(1);'];end
    end
    label=names{k};if ~isempty(action),label=[label newline 'en: ' action];end
    if k>1 && k<numel(names),label=[label newline 'on step: ' action];end
    ops{end+1}=reorg.add('State',names{k},names{k},struct('LabelString',label,'Position',[100+mod(k-1,3)*420 100+floor((k-1)/3)*300 325 220]));
end
ops{end+1}=reorg.add('Junction','ResumePhase','resume',struct('Position',[490 410 12 12]));
ops{end+1}=reorg.transition('?','#Idle', ...
    '/counter=uint16(0);buttonCount=uint8(0);rate=single(0);didReset=false;trimThrust=single(0);domega=single(0);quarter=uint16(40);flipStep=uint16(160);restartPhase=false;',1);
reply=reorg.edit(model,phases,ops,'full');ids=struct;
for k=1:numel(names),ids.(names{k})=reorg.created(reply,names{k});end
resume=reorg.created(reply,'resume');
ops={reorg.transition(phases,ids.Idle,'step[branch~=6]',1), ...
    reorg.transition(phases,ids.Boost,'step[branch==6 && restartPhase]',2), ...
    reorg.transition(ids.Idle,resume,'step[branch==6]',1)};
limits={'180','180+quarter','180+2*quarter','180+3*quarter','180+flipStep','190+flipStep','380+flipStep'};
for k=2:numel(names)
    if k<numel(names)
        ops{end+1}=reorg.transition(resume,ids.(names{k}),['[counter<' limits{k-1} ']'],k-1);
        ops{end+1}=reorg.transition(ids.(names{k}),ids.(names{k+1}),['step[counter>=' limits{k-1} ']'],1);
    else
        ops{end+1}=reorg.transition(resume,ids.(names{k}),'',k-1);
        ops{end+1}=reorg.transition(ids.Complete,ids.Boost,'step',1);
    end
end
reorg.edit(model,id,ops);
code=sprintf([ ...
    'start=false;done=false;phase=uint8(0);thrust=single(0);rollRate=single(0);angleReset=false;ahrsReset=false;normalControl=true;\n' ...
    'restartPhase=branch==3 || previousReset;\n' ...
    'if restartPhase,counter=uint16(0);rate=single(0);didReset=false;end\n' ...
    'if branch==6\n' ...
    ' rate=lastRate(1);\n' ...
    ' trimThrust=single(double(-single(.2448)*voltage+single(1.5892))*3.7);\n' ...
    ' flipStep=uint16(fix(single(.4)/single(.0025)));quarter=idivide(flipStep,uint16(4));\n' ...
    ' domega=single(double(single(.00217))*8*pi/double(single(.4))/double(single(.4)));\n' ...
    'end\n' ...
    'send(step,FlipPhases);\n' ...
    'if branch==2 || (branch==6 && normalControl)\n' ...
    ' if button==1\n' ...
    '  buttonCount=buttonCount+uint8(1);\n' ...
    '  if buttonCount>uint8(10),buttonCount=uint8(0);start=true;end\n' ...
    ' else,buttonCount=uint8(0);end\n' ...
    'end']);
parentPosition=sfroot().find('-isa','Stateflow.Chart','Path',reorg.path(model,id)).find('-isa','Stateflow.State','Name','FlipPhases').Position;
cyclePosition=[parentPosition(1)+parentPosition(3)+2000 parentPosition(2) 730 750];
ops={reorg.add('State','CycleInputs','cycle',struct('LabelString',['CycleInputs' newline 'en: ' code newline 'du: ' code], ...
    'ExecutionOrder',2,'Position',cyclePosition)), ...
    reorg.add('Annotation','JapaneseExplanation','note',struct('Text',description,'Position',[50 1150 1700 150]))};
reorg.edit(model,id,ops);
report=struct('StateNames',{names},'NoMATLABFunctions',true);
save_system(model);
end
