function parameters=init_kf_flight()
%INIT_KF_FLIGHT Initialize the standard altitude Kalman flight model.
% No hardware is opened and no flight command is sent.
parameters=init_imu_flight();
settings=struct('SampleTime',0.0025, ...
    'ProcessParameters',single([0.01;1;0.01]), ...
    'MeasurementVariance',single(0.004^2), ...
    'InitialState',zeros(3,1,'single'), ...
    'InitialCovariance',single(100)*eye(3,'single'));
% ProcessParameters: velocity noise variance, bias noise variance, bias decay.
assignin('base','AltitudeKF',settings);
end
