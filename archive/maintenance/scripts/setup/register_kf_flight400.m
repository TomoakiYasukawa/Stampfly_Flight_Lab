function report=register_kf_flight400()
%REGISTER_KF_FLIGHT400 Register the validated standard Kalman flight copy.
root=stampfly_project_root();
project=matlab.project.loadProject(fullfile(root,'StampFly_Official.prj'));
files={'archive/kf400/StampFly_KF400.slx','README.md','firmware/README.md','docs/history/kf_flight_model.md', ...
    'docs/history/altitude_kalman_replacement_review.md','config/stampfly_model_file.m', ...
    'code/model_algorithms/KF400Schedule.m','code/model_algorithms/KF400CurrentState.m', ...
    'code/model_algorithms/KF400FlightOutputs.m','code/+official/TickStart400.m','src/official_scheduler.cpp', ...
    'archive/maintenance/scripts/setup/init_kf_flight.m','archive/maintenance/scripts/setup/register_kf_flight400.m', ...
    'archive/maintenance/scripts/model_edit/create_kf_flight400.m','archive/maintenance/scripts/model_edit/layout_kf400.m', ...
    'archive/maintenance/scripts/verification/verify_kf_altitude400.m','archive/maintenance/scripts/verification/analyze_kf_altitude400.m', ...
    'archive/maintenance/scripts/verification/verify_kf_flight400.m','archive/maintenance/scripts/verification/assess_kf_flight400.m', ...
    'archive/maintenance/scripts/build/build_kf_flight400.m','archive/maintenance/tools/deploy_kf_firmware.py','tools/capture_imu_startup.py', ...
    'docs/history/kf_flight_structure.json','docs/history/kf_altitude_verification.json','docs/history/kf_altitude_numerics.json', ...
    'docs/history/kf_flight_verification.json','docs/history/kf_flight_build.json','docs/history/kf_aircraft_deployment.json', ...
    'docs/history/kf_usb_startup.json','docs/kf_project_registration.json', ...
    'docs/history/images/kf_altitude400.png','docs/history/images/kf_filter_step400.png', ...
    'archive/kf400/firmware/StampFly_KF400.bin','archive/kf400/firmware/StampFly_KF400.bootloader.bin', ...
    'archive/kf400/firmware/StampFly_KF400.partitions.bin'};
record=fullfile(root,'docs','history','kf_project_registration.json');
if ~isfile(record),writeJSON(record,struct('RegistrationComplete',false));end
for k=1:numel(files)
    assert(isfile(fullfile(root,files{k})),'kf400:MissingFile','Missing %s',files{k});
    addFile(project,files{k});
end
for folder={'scripts/setup','scripts/model_edit','scripts/verification','scripts/build'}
    addPath(project,folder{1});
end
shortcut=addShortcut(project,'archive/kf400/StampFly_KF400.slx');shortcut.Name='機体モデル（IMU + Kalman）';
refreshSourceControl(project);checks=runChecks(project);updateDependencies(project);
summary=struct('ID',{},'Description',{},'Passed',{},'ProblemFileCount',{},'ProblemFileSamples',{});
for k=1:numel(checks)
    summary(k)=struct('ID',checks(k).ID,'Description',checks(k).Description, ...
        'Passed',checks(k).Passed,'ProblemFileCount',numel(checks(k).ProblemFiles), ...
        'ProblemFileSamples',{checks(k).ProblemFiles(1:min(5,numel(checks(k).ProblemFiles)))});
end
report=struct('Model','archive/kf400/StampFly_KF400.slx','ProjectFile','StampFly_Official.prj', ...
    'RegisteredFiles',{files},'RegistrationComplete',true,'Checks',summary, ...
    'ChecksPassed',all([checks.Passed]),'SourceControlIntegration',project.SourceControlIntegration, ...
    'DependencyNodeCount',numnodes(project.Dependencies), ...
    'DependencyEdgeCount',numedges(project.Dependencies));
writeJSON(record,report);
file=fullfile(root,'docs','history','kf_aircraft_deployment.json');deployment=jsondecode(fileread(file));
deployment.project_registration_record='docs/kf_project_registration.json';
deployment.project_checks_passed=report.ChecksPassed;writeJSON(file,deployment);
assert(report.ChecksPassed,'kf400:ProjectChecks','Project checks did not all pass.');
fprintf('KF400_PROJECT_REGISTERED\n');disp(report);
end
function writeJSON(file,report)
fid=fopen(file,'w','n','UTF-8');assert(fid>=0);fprintf(fid,'%s\n',jsonencode(report,'PrettyPrint',true));fclose(fid);
end
