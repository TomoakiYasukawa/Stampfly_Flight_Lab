function report=register_imu_readability400()
%REGISTER_IMU_READABILITY400 Register saved model, tools and deployment evidence.
root=stampfly_project_root();
project=matlab.project.loadProject(fullfile(root,'StampFly_Official.prj'));
files={'StampFly_IMU400.slx','README.md','docs/imu_flight_model.md','firmware/README.md', ...
    'archive/maintenance/scripts/model_edit/reorganize_imu400.m','archive/maintenance/scripts/model_edit/layout_imu400.m', ...
    'archive/maintenance/scripts/verification/verify_imu_readability400.m','archive/maintenance/scripts/build/build_imu_readability400.m', ...
    'archive/maintenance/scripts/setup/register_imu_readability400.m','archive/maintenance/tools/deploy_imu_readability.py', ...
    'tools/capture_imu_startup.py','docs/history/imu_readability_structure.json', ...
    'docs/history/imu_readability_verification.json','docs/history/imu_readability_build.json', ...
    'docs/history/imu_readability_aircraft_deployment.json','docs/history/imu_readability_usb_startup.json', ...
    'docs/history/imu_readability_usb_attempt1.json', ...
    'docs/history/imu_readability_project_registration.json', ...
    'firmware/history/imu400_readability/StampFly_IMU400.bin', ...
    'firmware/history/imu400_readability/StampFly_IMU400.bootloader.bin', ...
    'firmware/history/imu400_readability/StampFly_IMU400.partitions.bin'};
record=fullfile(root,'docs','history','imu_readability_project_registration.json');
if ~isfile(record),writeJSON(record,struct('RegistrationComplete',false));end
for k=1:numel(files)
    assert(isfile(fullfile(root,files{k})),'imu400:MissingFile','Missing %s',files{k});
    addFile(project,files{k});
end
for folder={'scripts/setup','scripts/model_edit','scripts/verification','scripts/build'}
    addPath(project,folder{1});
end
refreshSourceControl(project);checks=runChecks(project);updateDependencies(project);
summary=struct('ID',{},'Description',{},'Passed',{},'ProblemFileCount',{},'ProblemFileSamples',{});
for k=1:numel(checks)
    summary(k)=struct('ID',checks(k).ID,'Description',checks(k).Description, ...
        'Passed',checks(k).Passed,'ProblemFileCount',numel(checks(k).ProblemFiles), ...
        'ProblemFileSamples',{checks(k).ProblemFiles(1:min(5,numel(checks(k).ProblemFiles)))});
end
report=struct('Model','StampFly_IMU400.slx','ProjectFile','StampFly_Official.prj', ...
    'RegisteredFiles',{files},'RegistrationComplete',true,'Checks',summary, ...
    'ChecksPassed',all([checks.Passed]),'SourceControlIntegration',project.SourceControlIntegration, ...
    'DependencyNodeCount',numnodes(project.Dependencies), ...
    'DependencyEdgeCount',numedges(project.Dependencies));
writeJSON(record,report);
file=fullfile(root,'docs','history','imu_readability_aircraft_deployment.json');
deployment=jsondecode(fileread(file));
deployment.project_registration_record='docs/history/imu_readability_project_registration.json';
deployment.project_checks_passed=report.ChecksPassed;
writeJSON(file,deployment);
fprintf('IMU400_READABILITY_PROJECT_REGISTERED\n');disp(report);
assert(report.ChecksPassed,'imu400:ProjectChecks','Project checks did not all pass.');
end

function writeJSON(file,report)
fid=fopen(file,'w','n','UTF-8');assert(fid>=0);
fprintf(fid,'%s\n',jsonencode(report,'PrettyPrint',true));fclose(fid);
end
