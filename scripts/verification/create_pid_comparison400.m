function result=create_pid_comparison400()
%CREATE_PID_COMPARISON400 Compare an unchanged PID with a dedicated block.
% 機体とは独立した検討用モデル。本番のPIDは変更しない。
root=stampfly_project_root();
m='PIDBlockComparison400';
assert(~bdIsLoaded(m),'official:FreshPIDHarness','Use a fresh PID harness.');
new_system(m);open_system(m);
current='StampFly_Official_FlightTest400';load_system(fullfile(root,[current '.slx']));
model_read(current,'blk_3312','0');
reply=reorg.edit(m,'root',{reorg.add(reorg.path(current,'blk_3322'),'OriginalPID','original'), ...
    struct('op','create_subsystem','name','DedicatedCandidate','ref','candidate', ...
    'interface',struct('inputs',{{'Error','Dt','Enable','Reset','PreviousError'}},'outputs',{{'Output'}})), ...
    reorg.configure(['config:' m],struct('Solver','FixedStepDiscrete','FixedStep','.0025', ...
    'StopTime','1','SaveOutput','on','OutputSaveName','yout','SaveFormat','Dataset', ...
    'SaveTime','off','SignalLogging','off'))},'full');
result.OriginalID=reorg.created(reply,'original');result.CandidateID=reorg.created(reply,'candidate');
% Persist the measured model gains with the harness so reruns do not depend
% on ignored build/cache files or block IDs captured in a previous session.
production=fullfile(current,'FlightControl400','TakeoffHoverControl400');
pidPaths={ ...
    'AltitudePID','AltitudeControl400/AltitudePID'; ...
    'VerticalSpeedPID','AltitudeControl400/VerticalSpeedPID'; ...
    'RollAnglePID','AttitudeControl400/RollAnglePID'; ...
    'PitchAnglePID','AttitudeControl400/PitchAnglePID'; ...
    'RollRatePID','BodyRateControl400/RollRatePID'; ...
    'PitchRatePID','BodyRateControl400/PitchRatePID'; ...
    'YawRatePID','BodyRateControl400/YawRatePID'};
taskGains=struct;
for k=1:size(pidPaths,1)
    path=[production '/' pidPaths{k,2}];
    gain=struct('Path',path,'SID',str2double(get_param(path,'SID')));
    for parameter={'Kp','Ti','Td','Eta'}
        block=find_system(path,'SearchDepth',1,'Name',parameter{1});assert(numel(block)==1);
        gain.(parameter{1})=double(eval(get_param(block{1},'Value')));
    end
    switchPorts=get_param([path '/Select_output'],'PortHandles');
    disabledLine=get_param(switchPorts.Inport(3),'Line');
    disabledSource=get_param(get_param(disabledLine,'SrcPortHandle'),'Parent');
    gain.HoldOutput=strcmp(get_param(disabledSource,'Name'),'YMemory');
    assert(gain.HoldOutput,'official:PIDOutputHold','Expected the deployed graphical PID output hold.');
    taskGains.(pidPaths{k,1})=gain;
end
result.GainSets=taskGains;
scope=result.CandidateID;[ins,outs]=reorg.ports(m,scope);
reply=reorg.edit(m,scope,{struct('op','create_subsystem','name','EnabledPID','ref','enabled', ...
    'interface',struct('inputs',{{'Error','Dt','Reset'}},'outputs',{{'Output'}})), ...
    reorg.add('Terminator','UnusedPreviousError','unused')});
result.EnabledID=reorg.created(reply,'enabled');
reorg.edit(m,scope,{reorg.wire([ins{1} '.y1'],[result.EnabledID '.u1']), ...
    reorg.wire([ins{2} '.y1'],[result.EnabledID '.u2']), ...
    reorg.wire([ins{4} '.y1'],[result.EnabledID '.u3']), ...
    reorg.wire([ins{5} '.y1'],[reorg.created(reply,'unused') '.u1']), ...
    reorg.wire([result.EnabledID '.y1'],[outs{1} '.u1'])});
scope=result.EnabledID;[eIns,eOuts]=reorg.ports(m,scope);
reply=reorg.edit(m,scope,{reorg.add('simulink/Ports & Subsystems/Enable','Enable','enable', ...
    struct('StatesWhenEnabling','held')), ...
    reorg.add('simulink/Discrete/Discrete PID Controller','DedicatedPID','pid', ...
    struct('Form','Ideal','TimeDomain','Discrete-time','IntegratorMethod','Trapezoidal', ...
    'FilterMethod','Trapezoidal','SampleTime','.0025','UseExternalTs','on','UseKiTs','off', ...
    'ExternalReset','level','InitialConditionSource','external','LimitIntegrator','on', ...
    'UpperIntegratorSaturationLimit','single(30000)','LowerIntegratorSaturationLimit','single(-30000)', ...
    'P','single(.38)','I','single(1)/single(10)','D','single(.5)','N','single(1)/(single(.125)*single(.5))')), ...
    reorg.add('Constant','ZeroInitialCondition','zero',struct('Value','single(0)'))});
result.PIDID=reorg.created(reply,'pid');zero=reorg.created(reply,'zero');
reorg.edit(m,scope,{reorg.wire([eIns{1} '.y1'],[result.PIDID '.u1']), ...
    reorg.wire([eIns{3} '.y1'],[result.PIDID '.u2']), ...
    reorg.wire([zero '.y1'],[result.PIDID '.u3']),reorg.wire([zero '.y1'],[result.PIDID '.u4']), ...
    reorg.wire([eIns{2} '.y1'],[result.PIDID '.u5']),reorg.wire([result.PIDID '.y1'],[eOuts{1} '.u1'])});
% Enable is a control port, so use its library block to discover the endpoint.
enableLine=sprintf('%s.y1 -> %s.enable',ins{3},result.EnabledID);
reorg.edit(m,result.CandidateID,{struct('op','connect','target',enableLine)});
params=struct;metadata=get_param(reorg.path(m,result.PIDID),'ObjectParameters');
names=fieldnames(metadata);
for k=1:numel(names)
    if endsWith(names{k},'DataTypeStr') && ~startsWith(names{k},'FilterDiff')
        params.(names{k})='single';
    end
end
reorg.edit(m,result.EnabledID,{reorg.configure(result.PIDID,params)});
ops={};inputNames={'Error','Dt','Enable','Reset','PreviousError'};
for k=1:5
    datatype='single';if ismember(k,[3 4]),datatype='boolean';end
    ops{end+1}=reorg.add('Inport',inputNames{k},['input' num2str(k)], ...
        struct('Port',num2str(k),'OutDataTypeStr',datatype,'SampleTime','.0025')); %#ok<AGROW>
    ops{end+1}=reorg.wire(sprintf('#input%d.y1',k),sprintf('%s.u%d',result.OriginalID,k)); %#ok<AGROW>
    ops{end+1}=reorg.wire(sprintf('#input%d.y1',k),sprintf('%s.u%d',result.CandidateID,k)); %#ok<AGROW>
end
ops=[ops,{reorg.add('Outport','OriginalOutput','out1',struct('Port','1')), ...
    reorg.add('Outport','DedicatedOutput','out2',struct('Port','2')), ...
    reorg.wire([result.OriginalID '.y1'],'#out1.u1'),reorg.wire([result.CandidateID '.y1'],'#out2.u1')}];
reorg.edit(m,'root',ops,'full');
disp(model_check(m,'root','["all"]'));
save_system(m,stampfly_model_file(m));
save(fullfile(root,'build','tests','pid_comparison_ids.mat'),'result');
save(fullfile(root,'tests','pid_comparison_metadata.mat'),'result');
end
