function report=create_horizontal_closed_loop()
%CREATE_HORIZONTAL_CLOSED_LOOP 実7 PID・指令生成・配分と水平推定を剛体へ接続。
% 姿勢・高度は剛体真値を使います。IMU推定誤差を含まない範囲の試験です。
root=stampfly_project_root();addpath(fullfile(root,'tests'));horizontaltest.init();ensure_simulink_toolkit();
assert(library.settingsLookup().gatePass);m='StampFly_IMU400';open_system(fullfile(root,[m '.slx']));
h='HorizontalClosedLoop';if bdIsLoaded(h),close_system(h,0);end
new_system(h);open_system(h);
reply=reorg.edit(h,'root',{reorg.add(reorg.path(m,'blk_2274'),'FlightControl','control'), ...
    reorg.add(reorg.path(m,'blk_4298'),'FlowMotion','estimator')},'full');
controller=reorg.created(reply,'control');estimator=reorg.created(reply,'estimator');
ops={reorg.configure(['config:' h],struct('Solver','FixedStepDiscrete','FixedStep','.0025','StopTime','25', ...
    'SaveOutput','on','OutputSaveName','yout','SaveFormat','Dataset')), ...
    reorg.add('MATLABSystem','Plant','plant',struct('System','horizontaltest.Plant')), ...
    reorg.add('Inport','Sticks','sticks',struct('Port','1','PortDimensions','6','OutDataTypeStr','single','SampleTime','.0025')), ...
    reorg.add('Inport','Disturbance','disturbance',struct('Port','2','PortDimensions','2','OutDataTypeStr','single','SampleTime','.0025')), ...
    reorg.add('Inport','FlowQuality','quality',struct('Port','3','OutDataTypeStr','uint16','SampleTime','.0025')), ...
    reorg.add('Inport','Branch','branch',struct('Port','4','OutDataTypeStr','uint8','SampleTime','.0025')), ...
    reorg.add('Constant','Dt','dt',struct('Value','single(.0025)')), ...
    reorg.add('Constant','Voltage','voltage',struct('Value','single(3.8)')), ...
    reorg.add('Constant','SensorFlags','flags',struct('Value','zeros(3,1,''uint8'')')), ...
    reorg.add('Constant','ResetFalse','reset',struct('Value','false')), ...
    reorg.add('Constant','PoseReady','ready',struct('Value','true')), ...
    reorg.add('Constant','Connected','connected',struct('Value','uint8(1)')), ...
    reorg.add('BusCreator','PilotBus','pilot',struct('Inputs','4','OutDataTypeStr','Bus: HorizontalTestPilotBus','NonVirtualBus','on','InheritFromInputs','off')), ...
    reorg.add('BusCreator','Supervisor','supervisor',struct('Inputs','5','OutDataTypeStr','Bus: HorizontalTestSupervisorBus','NonVirtualBus','on','InheritFromInputs','off')), ...
    reorg.add('BusCreator','Context','context',struct('Inputs','3','OutDataTypeStr','Bus: HorizontalContextBus','NonVirtualBus','on','InheritFromInputs','off')), ...
    reorg.add('BusCreator','MotionBus','motion',struct('Inputs','6','OutDataTypeStr','Bus: HorizontalMotionBus','NonVirtualBus','on','InheritFromInputs','off')), ...
    reorg.add('BusSelector','MotorFields','duty',struct('OutputSignals','Duty,Counts')), ...
    reorg.add('UnitDelay','ActuatorInputDelay','actuatorDelay',struct('SampleTime','.0025', ...
        'InitialCondition','zeros(4,1,''single'')')), ...
    reorg.add('BusSelector','FlightFields','status',struct('OutputSignals','Diagnostics,Mode')), ...
    reorg.add('From','ReadHorizontalDiagnostics','diagnostics',struct('GotoTag','HorizontalControlDiagnostics')), ...
    reorg.wire('#plant.y1',[controller '.u1']),reorg.wire('#plant.y2',[controller '.u2']), ...
    reorg.wire('#pilot.y1',[controller '.u3']),reorg.wire('#supervisor.y1',[controller '.u4']),reorg.wire('#motion.y1',[controller '.u5']), ...
    reorg.wire([controller '.y1'],'#duty.u1'),reorg.wire('#duty.y1','#actuatorDelay.u1'), ...
    reorg.wire('#actuatorDelay.y1','#plant.u1'), ...
    reorg.wire('#disturbance.y1','#plant.u2'),reorg.wire('#quality.y1','#plant.u3'), ...
    reorg.wire('#plant.y3',[estimator '.u1']),reorg.wire('#plant.y4',[estimator '.u2']), ...
    reorg.wire('#plant.y5',[estimator '.u3']),reorg.wire('#context.y1',[estimator '.u4']), ...
    reorg.wire('#sticks.y1','#pilot.u1'),reorg.wire('#voltage.y1','#pilot.u2'), ...
    reorg.wire('#dt.y1','#pilot.u3'),reorg.wire('#flags.y1','#pilot.u4'), ...
    reorg.wire('#branch.y1','#supervisor.u1'),reorg.wire('#branch.y1','#supervisor.u2'), ...
    reorg.wire('#reset.y1','#supervisor.u3'),reorg.wire('#reset.y1','#supervisor.u4'),reorg.wire('#connected.y1','#supervisor.u5'), ...
    reorg.wire('#dt.y1','#context.u1'),reorg.wire('#reset.y1','#context.u2'),reorg.wire('#ready.y1','#context.u3'), ...
    reorg.wire([controller '.y2'],'#status.u1'), ...
    reorg.add('Terminator','Feedback','feedback'),reorg.wire([controller '.y3'],'#feedback.u1')};
for k=1:6,ops{end+1}=reorg.wire(sprintf('%s.y%d',estimator,k),sprintf('#motion.u%d',k));end %#ok<AGROW>
names={'Duty','Counts','FlightDiagnostics','Mode','HorizontalDiagnostics','TrueState','Position','Velocity','Heading','Height','FlowStatus','FlowDiagnostics'};
feeds={'#duty.y1','#duty.y2','#status.y1','#status.y2','#diagnostics.y1','#plant.y6', ...
    [estimator '.y1'],[estimator '.y2'],[estimator '.y3'],[estimator '.y4'],[estimator '.y5'],[estimator '.y6']};
for k=1:numel(names)
    ops{end+1}=reorg.add('Outport',names{k},sprintf('output%d',k),struct('Port',num2str(k))); %#ok<AGROW>
    ops{end+1}=reorg.wire(feeds{k},sprintf('#output%d.u1',k)); %#ok<AGROW>
end
reorg.edit(h,'root',ops,'full');
% コピー元のログ公開は制御結果の同一性確認にも使うため残します。
% 未使用の公開信号はGotoで終端され、実I/Oは含まれません。
set_param(h,'SimulationCommand','update');disp(model_check(h,'root','["all"]'));
folder=fullfile(root,'build','horizontal_control','harnesses');save_system(h,fullfile(folder,[h '.slx']));
report=struct('Model',[h '.slx'],'RealPIDCount',numel(find_system(h,'LookUnderMasks','all','Name','DedicatedPID')), ...
    'Estimator',estimator,'Controller',controller,'UncalibratedPlant',true,'UsesTrueAttitudeAndAltitude',true);
assert(report.RealPIDCount==7);save(fullfile(folder,'closed_loop_structure.mat'),'report');
fprintf('HORIZONTAL_CLOSED_LOOP_CREATED\n');
end
