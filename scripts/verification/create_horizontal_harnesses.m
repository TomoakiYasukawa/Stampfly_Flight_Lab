function report=create_horizontal_harnesses()
%CREATE_HORIZONTAL_HARNESSES 保存済みの実ブロックを使い、物理I/Oなしの検証モデルを作る。
root=stampfly_project_root();init_imu_flight();ensure_simulink_toolkit();assert(library.settingsLookup().gatePass);
m='StampFly_IMU400';open_system(fullfile(root,[m '.slx']));
s=jsondecode(fileread(fullfile(root,'docs','horizontal_control_structure.json')));
folder=fullfile(root,'build','horizontal_control','harnesses');if ~isfolder(folder),mkdir(folder);end
h='HorizontalControllerTest';if bdIsLoaded(h),close_system(h,0);end
new_system(h);open_system(h);
reply=reorg.edit(h,'root',{reorg.add(reorg.path(m,s.Controller),'ControllerUnderTest','controller')},'full');
controller=reorg.created(reply,'controller');
[~,~,~,~,motion,context]=horizontal.fixture();
assignin('base','HorizontalTestMotion',motion);assignin('base','HorizontalTestContext',context);
names={'RollAngle','PitchAngle','VelocityX','VelocityY','PositionX','PositionY','Valid','Heading','Height','MotorSaturated'};
types={'single','single','single','single','single','single','single','single','single','boolean'};
ops={reorg.configure(['config:' h],struct('Solver','FixedStepDiscrete','FixedStep','.0025','StopTime','5', ...
    'SaveOutput','on','OutputSaveName','yout','SaveFormat','Dataset')), ...
    reorg.add('Constant','InitialMotion','motion',struct('Value','HorizontalTestMotion','OutDataTypeStr','Bus: HorizontalMotionBus')), ...
    reorg.add('Constant','ControlContext','context',struct('Value','HorizontalTestContext','OutDataTypeStr','Bus: HorizontalControlContextBus')), ...
    reorg.add('BusAssignment','MotionInputs','assign',struct('AssignedSignals','Velocity,Position,Status,Heading,Height')), ...
    reorg.add('Mux','ManualRP','manual',struct('Inputs','2')), ...
    reorg.add('Mux','VelocityXY','velocity',struct('Inputs','2')), ...
    reorg.add('Mux','PositionXY','position',struct('Inputs','2')), ...
    reorg.add('PulseGenerator','ObservationUpdate50','updated',struct('PulseType','Time based', ...
        'Amplitude','1','Period','.02','PulseWidth','12.5','PhaseDelay','.0175','SampleTime','.0025')), ...
    reorg.add('DataTypeConversion','UpdateToSingle','updatedSingle',struct('OutDataTypeStr','single')), ...
    reorg.add('Constant','MotionStatusRest','statusRest',struct('Value','single([.02;0;0;1;0;0])')), ...
    reorg.add('Mux','Status8','status',struct('Inputs','3')), ...
    reorg.wire('#updated.y1','#updatedSingle.u1'),reorg.wire('#updatedSingle.y1','#status.u2')};
for k=1:numel(names)
    ops{end+1}=reorg.add('Inport',names{k},['input' num2str(k)],struct('Port',num2str(k),'OutDataTypeStr',types{k},'SampleTime','.0025')); %#ok<AGROW>
end
for k=1:6
    ref={'manual','manual','velocity','velocity','position','position'};port=mod(k-1,2)+1;
    ops{end+1}=reorg.wire(sprintf('#input%d.y1',k),sprintf('#%s.u%d',ref{k},port)); %#ok<AGROW>
end
ops=[ops {reorg.wire('#input7.y1','#status.u1'),reorg.wire('#statusRest.y1','#status.u3'), ...
    reorg.wire('#motion.y1','#assign.u1'),reorg.wire('#velocity.y1','#assign.u2'), ...
    reorg.wire('#position.y1','#assign.u3'),reorg.wire('#status.y1','#assign.u4'), ...
    reorg.wire('#input8.y1','#assign.u5'),reorg.wire('#input9.y1','#assign.u6'), ...
    reorg.wire('#assign.y1',[controller '.u1']),reorg.wire('#manual.y1',[controller '.u2']), ...
    reorg.wire('#context.y1',[controller '.u3']),reorg.wire('#input10.y1',[controller '.u4']), ...
    reorg.add('Demux','SelectedAngles','angles',struct('Outputs','2')),reorg.wire([controller '.y1'],'#angles.u1'), ...
    reorg.add('Outport','SelectedRoll','roll',struct('Port','1')),reorg.wire('#angles.y1','#roll.u1'), ...
    reorg.add('Outport','SelectedPitch','pitch',struct('Port','2')),reorg.wire('#angles.y2','#pitch.u1'), ...
    reorg.add('Outport','Diagnostics24','diag',struct('Port','3')),reorg.wire([controller '.y2'],'#diag.u1')}];
reorg.edit(h,'root',ops,'full');disp(model_check(h,'root','["all"]'));save_system(h,fullfile(folder,[h '.slx']));
% Gherkin評価には診断ベクトルの実成分をスカラー端子で公開します。
% テストツールのベクトル要素評価に依存せず、保存ブロックの出力を観測します。
indices=[16 15 11 12];scalarNames={'State','Blend','IntegralX','IntegralY'};ops={};
for k=1:numel(indices)
    ops{end+1}=reorg.add('Selector',[scalarNames{k} 'Field'],sprintf('field%d',k), ...
        struct('InputPortWidth','24','Indices',num2str(indices(k)))); %#ok<AGROW>
    ops{end+1}=reorg.add('Outport',scalarNames{k},sprintf('scalar%d',k),struct('Port',num2str(3+k))); %#ok<AGROW>
    ops{end+1}=reorg.wire([controller '.y2'],sprintf('#field%d.u1',k)); %#ok<AGROW>
    ops{end+1}=reorg.wire(sprintf('#field%d.y1',k),sprintf('#scalar%d.u1',k)); %#ok<AGROW>
end
reorg.edit(h,'root',ops);save_system(h,fullfile(folder,[h '.slx']));
% 推定器は実際の4入力・6出力のSystemブロックをコピーします。
h2='HorizontalEstimatorTest';if bdIsLoaded(h2),close_system(h2,0);end
new_system(h2);open_system(h2);
tracker=find_system(reorg.path(m,s.Estimator),'LookUnderMasks','all','SearchDepth',1,'BlockType','MATLABSystem','System','horizontal.FlowMotion');
assert(isscalar(tracker));
ops={reorg.configure(['config:' h2],struct('Solver','FixedStepDiscrete','FixedStep','.0025','StopTime','1', ...
    'SaveOutput','on','OutputSaveName','yout','SaveFormat','Dataset')), ...
    reorg.add(tracker{1},'TrackerUnderTest','tracker')};
types={'HorizontalFlowBus','HorizontalInertialBus','HorizontalRangeBus','HorizontalContextBus'};
names={'OpticalFlow','InertialMotion','RangeMotion','Context'};
for k=1:4
    ops{end+1}=reorg.add('Inport',names{k},sprintf('input%d',k),struct('Port',num2str(k),'OutDataTypeStr',['Bus: ' types{k}],'SampleTime','.0025')); %#ok<AGROW>
    ops{end+1}=reorg.wire(sprintf('#input%d.y1',k),sprintf('#tracker.u%d',k)); %#ok<AGROW>
end
names={'Position','Velocity','Heading','Height','Status','Diagnostics'};
for k=1:6
    ops{end+1}=reorg.add('Outport',names{k},sprintf('output%d',k),struct('Port',num2str(k))); %#ok<AGROW>
    ops{end+1}=reorg.wire(sprintf('#tracker.y%d',k),sprintf('#output%d.u1',k)); %#ok<AGROW>
end
reorg.edit(h2,'root',ops,'full');disp(model_check(h2,'root','["all"]'));save_system(h2,fullfile(folder,[h2 '.slx']));
report=struct('ControllerHarness',fullfile(folder,[h '.slx']),'EstimatorHarness',fullfile(folder,[h2 '.slx']));
save(fullfile(folder,'harnesses.mat'),'report');fprintf('HORIZONTAL_REAL_BLOCK_HARNESSES_CREATED\n');
end
