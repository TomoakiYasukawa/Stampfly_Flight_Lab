function define(name,names,dimensions,types)
elements(1,numel(names))=Simulink.BusElement;
for k=1:numel(names)
    elements(k).Name=names{k};
    elements(k).Dimensions=dimensions(k);
    elements(k).DataType=types{k};
end
bus=Simulink.Bus;bus.Elements=elements;
bus.Description='StampFly 記録専用の型付き信号グループ';
assignin('base',name,bus);
end
