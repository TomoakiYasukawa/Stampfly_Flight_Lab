function p = init_official()
%INIT_OFFICIAL Parameters of M5Stack's 2024 StampFly controller.
setup_imu_monitor();
p = struct('Step',0.0025,'PWMHz',uint32(150000),'PWMBits',uint8(8), ...
    'AltitudeInitial',single(0.5),'AltitudeMin',single(0.05), ...
    'AltitudeMax',single(1.8),'DutyMax',single(0.95), ...
    'MotorOutputEnabled',false,'RadioChannel',uint8(3), ...
    'BuildID',uint16(1401));
assignin('base','Official',p);
% Typed diagnostic interface: a root output cannot export a mixed virtual bus.
names={'AppliedCounts','PWMStatus','Timing','Scheduler','ComputedDuty','OfficialMode', ...
 'FrontRange','Temp','Attitude','Rates','SensorFlags','ModeBeforeTick','RadioQueued', ...
 'LEDMode','RCConnected','BatteryV','RawMadgwickQuaternion','JoyTelemetrySent','ToFDiagnostics'};
dimensions=[4 4 8 4 4 1 1 1 3 3 3 1 1 1 1 1 4 1 4];
types={'uint8','uint32','uint32','uint32','single','uint8','int16','single','single','single', ...
 'uint8','uint8','uint8','uint8','uint8','single','single','uint8','uint32'};
for k=1:numel(names),elements(k)=Simulink.BusElement;elements(k).Name=names{k};elements(k).Dimensions=dimensions(k);elements(k).DataType=types{k};end
bus=Simulink.Bus;bus.Elements=elements;assignin('base','OfficialDiagnosticBus',bus);
init_logging_buses();
end
