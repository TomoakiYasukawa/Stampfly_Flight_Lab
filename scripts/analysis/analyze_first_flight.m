function result = analyze_first_flight(recordingPath)
%ANALYZE_FIRST_FLIGHT Preserve first real-flight evidence without filling gaps.
% MATLAB の記録済み SFI8 を解析します。機体へ指令を送りません。
arguments
    recordingPath (1,1) string
end
root = stampfly_project_root();
data = load(recordingPath);
assert(data.info.Complete, 'official:IncompleteLog', 'Stop and save recording first.');
telemetry = array2table(data.telemetry, 'VariableNames', data.info.Columns);
flightRows = find(telemetry.FlightState == 2 | telemetry.FlightState == 5);
assert(~isempty(flightRows), 'official:NoFlight', 'No flight state in the recording.');
first = flightRows(1);
last = flightRows(end);
flight = telemetry(flightRows,:);
startTime = telemetry.TimeSeconds(first);
relativeTime = flight.TimeSeconds - startTime;
sequenceSteps = mod(diff(flight.Sequence), 65536);
missing = sum(max(sequenceSteps - 1, 0));
expected = height(flight) + missing;

quaternion = table2array(flight(:, {'QuatW','QuatX','QuatY','QuatZ'}));
quaternion = quaternion ./ vecnorm(quaternion, 2, 2);
roll = atan2(2*(quaternion(:,1).*quaternion(:,2) + quaternion(:,3).*quaternion(:,4)), ...
    1 - 2*(quaternion(:,2).^2 + quaternion(:,3).^2))*180/pi;
pitchSine = 2*(quaternion(:,1).*quaternion(:,3) - quaternion(:,4).*quaternion(:,2));
pitch = asin(max(-1, min(1, pitchSine)))*180/pi;
hoverWindow = relativeTime >= 4 & relativeTime < 6;

result = struct( ...
    'Recording', char(recordingPath), ...
    'UserReport', 'Takeoff, short hovering and landing completed', ...
    'LandingMethodConfirmed', false, ...
    'TotalFrames', data.info.ValidFrames, ...
    'TotalMissingFrames', data.info.MissingFrames, ...
    'CRCRejected', data.info.CRCRejected, ...
    'FlightFrames', height(flight), ...
    'FlightStateSpanSeconds', flight.TimeSeconds(end) - startTime, ...
    'FlightMissingFrames', missing, ...
    'FlightMissingFraction', missing/expected, ...
    'MaximumFlightLogGapSeconds', max(diff(flight.TimeSeconds)), ...
    'LandingStateFrames', nnz(flight.FlightState == 5), ...
    'TargetHeightM', median(flight.ZReferenceM, 'omitmissing'), ...
    'MaximumEstimatedHeightM', max(flight.HeightM, [], 'omitmissing'), ...
    'MaximumToFDistanceM', max(flight.ToFDistanceM, [], 'omitmissing'), ...
    'HoverWindowFromStartSeconds', [4 6], ...
    'HoverWindowFrames', nnz(hoverWindow), ...
    'HoverWindowSampleMeanHeightM', mean(flight.HeightM(hoverWindow), 'omitmissing'), ...
    'HoverWindowHeightRangeM', [min(flight.HeightM(hoverWindow), [], 'omitmissing') ...
        max(flight.HeightM(hoverWindow), [], 'omitmissing')], ...
    'ToFValidFraction', mean(flight.ToFValid), ...
    'IMUFreshFraction', mean(flight.IMUValid), ...
    'BatteryReadSuccessFraction', mean(flight.BatteryReadSuccess), ...
    'FlightBatteryVoltageRangeV', [min(flight.BatteryVoltageV) max(flight.BatteryVoltageV)], ...
    'MaximumLoggedRollDeg', max(abs(roll), [], 'omitmissing'), ...
    'MaximumLoggedPitchDeg', max(abs(pitch), [], 'omitmissing'), ...
    'MaximumComputedMotorCount', double(max(data.rawFrames(flightRows,105:108), [], 'all')), ...
    'ActualMotorOutputRecorded', false);

transitionRows = [1; find(diff(telemetry.FlightState) ~= 0) + 1];
endRows = [transitionRows(2:end)-1; height(telemetry)];
result.StateIntervals = table(telemetry.FlightState(transitionRows), ...
    telemetry.TimeSeconds(transitionRows), telemetry.TimeSeconds(endRows), ...
    endRows-transitionRows+1, 'VariableNames', {'State','StartSeconds','EndSeconds','Frames'});
result.Caveats = { ...
    'No interpolation across missing radio packets', ...
    'No LANDING state received; landing method needs user clarification', ...
    'Highest recorded range is not a guaranteed peak because packets are missing', ...
    'Motor bytes are computed commands; physical applied output is not logged', ...
    'No onboard task timing stream over COM9 during battery-powered flight'};

% 1枚の高度図。欠落が60 msを超えた区間は線を切り、補間しません。
selected = telemetry.TimeSeconds >= startTime-0.5 & ...
    telemetry.TimeSeconds <= telemetry.TimeSeconds(last)+0.5;
shown = telemetry(selected,:);
elapsed = shown.TimeSeconds - startTime;
estimated = shown.HeightM;
range = shown.ToFDistanceM;
estimated(shown.HeightValid == 0) = NaN;
range(shown.ToFValid == 0) = NaN;
longGap = [false; diff(shown.TimeSeconds) > 0.0601];
estimated(longGap) = NaN;
range(longGap) = NaN;
fig = figure('Name', 'StampFly 初回飛行：高度ログ', 'Color', 'white');
ax = axes(fig);
ax.FontName = 'Meiryo';
plot(ax, elapsed, estimated, '.-', 'LineWidth', 1.2, 'MarkerSize', 7, ...
    'DisplayName', '高度Kalman');
hold(ax, 'on');
plot(ax, elapsed, range, '.', 'MarkerSize', 6, 'DisplayName', '下向きToF');
yline(ax, 0.5, '--', '目標 0.5 m', 'DisplayName', '目標高度');
if last < height(telemetry)
    xline(ax, telemetry.TimeSeconds(last+1)-startTime, ':', '待機へ遷移', ...
        'HandleVisibility', 'off');
end
hold(ax, 'off');
xlabel(ax, '最初のFLIGHT受信からの時間 [s]');
ylabel(ax, '高度・距離 [m]');
title(ax, '初回飛行：離陸後の高度推移');
subtitle(ax, sprintf('飛行区間 %dフレーム / 欠落 %.1f%% / 最大欠落間隔 %.2f s', ...
    result.FlightFrames, 100*result.FlightMissingFraction, result.MaximumFlightLogGapSeconds));
grid(ax, 'on');
legend(ax, 'Location', 'northwest');
xlim(ax, [elapsed(1) elapsed(end)]);
ylim(ax, [0 max(1, max(shown.ToFDistanceM, [], 'omitmissing')+0.1)]);
exportgraphics(ax, fullfile(root,'logs','first_flight_height.png'), 'Resolution', 180);
exportgraphics(ax, fullfile(root,'logs','first_flight_height.pdf'), 'ContentType', 'vector');
savefig(fig, fullfile(root,'logs','first_flight_height.fig'));
save(fullfile(root,'logs','first_flight_analysis.mat'), 'result');
fid = fopen(fullfile(root,'logs','first_flight_analysis.json'), 'w', 'n', 'UTF-8');
assert(fid >= 0, 'official:ReportWrite', 'Cannot open report.');
cleanup = onCleanup(@() fclose(fid));
fprintf(fid, '%s\n', jsonencode(result, 'PrettyPrint', true));
disp(result);
end
