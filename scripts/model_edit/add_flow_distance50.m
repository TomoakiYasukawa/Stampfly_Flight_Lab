function result=add_flow_distance50()
%ADD_FLOW_DISTANCE50 独立した4入力の距離換算ブロック。出力はロガーのみ。
model='StampFly_PIDBlock_FlightTest400';init_logging_buses();
reply=reorg.edit(model,'root',{struct('op','create_subsystem','name','OpticalFlowDistance50','ref','distance', ...
    'interface',struct('inputs',{{'OpticalFlow','Attitude','BottomRange','RawIMU'}},'outputs',{{'FlowDistance'}}))});
result.ID=reorg.created(reply,'distance');[ins,outs]=reorg.ports(model,result.ID);
reply=reorg.edit(model,result.ID,{ ...
    reorg.add('BusSelector','FlowFields','flow',struct('OutputSignals','Totals,Raw')), ...
    reorg.add('BusSelector','AttitudeFields','attitude',struct('OutputSignals','Angles')), ...
    reorg.add('BusSelector','RangeFields','range',struct('OutputSignals','DistanceMm')), ...
    reorg.add('BusSelector','IMUFields','imu',struct('OutputSignals','AngularRate')), ...
    reorg.add('DataTypeConversion','RangeToSingle','cast',struct('OutDataTypeStr','single')), ...
    reorg.add('Gain','MillimetersToMeters','meters',struct('Gain','single(.001)')), ...
    reorg.add('Mux','PoseAndRange4','geometry',struct('Inputs','2')), ...
    reorg.add('MATLABSystem','GroundMotionDistance','convert',struct('System','imu.FlowDistance50')), ...
    reorg.add('BusCreator','DistanceData','bus',struct('Inputs','3','OutDataTypeStr','Bus: LogDistanceBus','NonVirtualBus','on')), ...
    reorg.wire([ins{1} '.y1'],'#flow.u1','OpticalFlow'),reorg.wire([ins{2} '.y1'],'#attitude.u1','Attitude'), ...
    reorg.wire([ins{3} '.y1'],'#range.u1','BottomRange'),reorg.wire([ins{4} '.y1'],'#imu.u1','RawIMU'), ...
    reorg.wire('#range.y1','#cast.u1','DistanceMm'),reorg.wire('#cast.y1','#meters.u1'), ...
    reorg.wire('#meters.y1','#geometry.u2','ToFRangeM'),reorg.wire('#attitude.y1','#geometry.u1','AnglesRad'), ...
    reorg.wire('#flow.y1','#convert.u1','FlowTotals'),reorg.wire('#flow.y2','#convert.u2','FlowRaw'), ...
    reorg.wire('#imu.y1','#convert.u3','GyroRawRadps'),reorg.wire('#geometry.y1','#convert.u4','PoseAndRange'), ...
    reorg.wire('#convert.y1','#bus.u1','PositionEN'),reorg.wire('#convert.y2','#bus.u2','Used'), ...
    reorg.wire('#convert.y3','#bus.u3','DeltaEN'),reorg.wire('#bus.y1',[outs{1} '.u1'],'FlowDistance')},'full');
reorg.note(model,result.ID, ...
    '移動距離への換算（表示・記録専用）\n400 Hzの累積Flow差分を50 Hzで集計。ToFの高さでmに換算し、ジャイロで傾きによる見かけの動きを補正。\n姿勢で東・北へ変換して積算。385 count/radは未校正の初期値です。飛行制御には接続しません。',[20 20 1150 135]);
reorg.edit(model,'root',{ ...
    reorg.wire('blk_3979.y1',[result.ID '.u1'],'OpticalFlow'), ...
    reorg.wire('blk_2231.y1',[result.ID '.u2'],'Attitude'), ...
    reorg.wire('blk_3178.y1',[result.ID '.u3'],'BottomRange'), ...
    reorg.wire('blk_3161.y1',[result.ID '.u4'],'RawIMU'), ...
    reorg.configure(result.ID,struct('Mask','on','MaskDisplay', ...
        'disp(''Flow移動距離 [m]\n50 Hz / 表示・記録専用'')','FontSize','11'))});
reply=reorg.edit(model,'blk_2963',{ ...
    reorg.add('Inport','FlowDistance','distance',struct('Port','3')), ...
    reorg.configure('blk_4034',struct('Inputs','5')),reorg.wire('#distance.y1','blk_4034.u5','Distance')});
reorg.edit(model,'root',{reorg.wire([result.ID '.y1'],'blk_2963.u3','FlowDistance')});
finish_flow_distance50();
disp(model_check(model,result.ID,'["all"]'));disp(model_check(model,'blk_2963','["all"]'));
disp(model_check(model,'root','["all"]'));save_system(model,[],'OverwriteIfChangedOnDisk',true);
end
