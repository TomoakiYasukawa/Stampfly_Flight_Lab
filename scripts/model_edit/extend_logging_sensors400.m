function report=extend_logging_sensors400()
%EXTEND_LOGGING_SENSORS400 計測専用センサーと4バスのログ入力を追加する。
% PID・推定・状態遷移の計算内容は変更しない。構造編集はSATK経由。
root=stampfly_project_root();model='StampFly_PIDBlock_FlightTest400';
ensure_simulink_toolkit();assert(library.settingsLookup().gatePass);
open_system(fullfile(root,[model '.slx']));
assert(strcmp(get_param(model,'SimulationStatus'),'stopped'));
model_read(model,'root','0');
% Take off all data fields from the existing data paths, only for logging.
tapCorrection(model);
existing=find_system(model,'SearchDepth',1,'Name','OpticalFlowSensor400');
if isempty(existing)
reply=reorg.edit(model,'root',{ ...
    struct('op','create_subsystem','name','OpticalFlowSensor400','ref','flow', ...
        'interface',struct('inputs',{{}},'outputs',{{'OpticalFlow'}})), ...
    struct('op','create_subsystem','name','MagnetometerSensor400','ref','mag', ...
        'interface',struct('inputs',{{}},'outputs',{{'MagneticField'}}))});
report.FlowID=reorg.created(reply,'flow');report.MagID=reorg.created(reply,'mag');
else
    report.FlowID=reorg.id(existing{1});
    existing=find_system(model,'SearchDepth',1,'Name','MagnetometerSensor400');
    report.MagID=reorg.id(existing{1});
end
sensor(model,report.FlowID,'stampfly.PMW3901MB',{'Delta','Raw','Info','Totals'}, ...
    '光学フロー取得専用：400 Hz / SPI 2 MHz。生カウント・品質・読出し時間を出力。制御には接続しません。');
sensor(model,report.MagID,'stampfly.BMM150',{'Field','Flags','Info'}, ...
    '磁気取得専用：BMM150の新規測定30 Hz。400 Hz側はcore0の最新値を非待機で受け取ります。');
reorg.edit(model,'root',{ ...
    reorg.configure(report.FlowID,icon('Optical Flow 取得','400 Hz / 記録専用',[60 1080 320 1205])), ...
    reorg.configure(report.MagID,icon('磁気取得','30 Hz / 最新値は400 Hz',[60 1260 320 1380]))});
% Replace the old 17-port logger wrapper with readable grouped input buses.
scope='blk_2963';model_read(model,scope,'0');
blocks=find_system(reorg.path(model,scope),'SearchDepth',1,'Type','Block');ops={};
for k=2:numel(blocks)
    id=reorg.id(blocks{k});
    if ismember(id,{'blk_2966','blk_2967','blk_2968','blk_3304'}),continue;end
    ops{end+1}=struct('op','delete','target',id); %#ok<AGROW>
end
ops=[ops,{ ...
    reorg.add('Inport','OpticalFlow','flow',struct('Port','1')), ...
    reorg.add('Inport','MagneticField','mag',struct('Port','2')), ...
    reorg.add('MATLABSystem','TelemetryPacker50','packer',struct('System','official.ExtendedLogger50')), ...
    reorg.add('MATLABSystem','RadioUSBTransport50','transport',struct('System','official.LogTransport50')), ...
    reorg.wire('#packer.y1','#transport.u1','SFI8Frame190'), ...
    reorg.wire('#packer.y2','#transport.u2','CommandFrame190'), ...
    reorg.wire('#packer.y3','#transport.u3','SensorFrame246'), ...
    reorg.wire('#transport.y1','blk_2966.u1','USBDrops'), ...
    reorg.wire('#transport.y2','blk_2967.u1','RadioQueued'), ...
    reorg.wire('#transport.y3','blk_2968.u1','LEDMode')}];
reply=reorg.edit(model,scope,ops,'full');
flowIn=reorg.created(reply,'flow');magIn=reorg.created(reply,'mag');packer=reorg.created(reply,'packer');
raw={'RawAcceleration','Acceleration';'RawAngularRate','AngularRate';'IMUSampleFresh','IMUFresh'; ...
    'TimeSeconds','Time';'BottomDistanceMm','BottomMm';'BottomRangeFresh','ToFFresh'; ...
    'BottomRangeStatus','ToFStatus';'BatteryVoltage','Voltage';'BatteryReadValid','BatteryValid'; ...
    'BottomToFDiagnostics','ToFInfo';'IMUTemperature','Temperature'};
estimate={'AttitudeAngles','Angles';'EstimatedAltitude','Height';'VerticalVelocity','Velocity'; ...
    'ControlDiagnostics','ControlDiagnostics';'SensorDiagnostics','SensorDiagnostics'; ...
    'FilteredAcceleration','FilteredAccel';'FilteredAngularRate','FilteredGyro'; ...
    'AttitudeQuaternion','Quaternion';'SensorFlags','Flags'};
commands={'MotorDuty','Duty';'AppliedPWMCounts','AppliedCounts';'PWMStatus','PWMStatus'; ...
    'JoystickPacketError','PacketError';'JoystickConnected','Connected';'AltitudeEnabled','AltitudeEnabled'; ...
    'FlipPhase','FlipPhase';'PreviousMode','PreviousMode';'FlightMode','Mode'; ...
    'SamplePeriod','Dt';'CycleStartUs','StartUs';'JoystickSticks','UsedSticks'};
ops={};
[ops,rawBus]=fromBus(ops,raw,'RawSensors');
[ops,estimateBus]=fromBus(ops,estimate,'Estimates');
[ops,commandBus]=fromBus(ops,commands,'Commands',2);
ops=[ops,{reorg.add('From','ReadJoystickPilot','pilot',struct('GotoTag','JoystickPilot')), ...
    reorg.wire('#pilot.y1',[commandBus '.u13'],'Pilot'), ...
    reorg.add('Constant','MotorOutputEnabled','enabled',struct('Value','true','OutDataTypeStr','boolean')), ...
    reorg.wire('#enabled.y1',[commandBus '.u14'],'OutputEnabled'), ...
    reorg.add('BusCreator','ExtraSensorsBus','extra',struct('Inputs','4')), ...
    reorg.wire([flowIn '.y1'],'#extra.u1','Flow'),reorg.wire([magIn '.y1'],'#extra.u2','Mag'), ...
    reorg.add('From','ReadCycleTiming','timing',struct('GotoTag','CycleTiming')), ...
    reorg.add('UnitDelay','PreviousCycleTiming','timingDelay',struct('InitialCondition','zeros(8,1,''uint32'')','SampleTime','.0025')), ...
    reorg.wire('#timing.y1','#timingDelay.u1','CycleTiming'),reorg.wire('#timingDelay.y1','#extra.u3','Timing'), ...
    reorg.add('From','ReadSchedulerStatus','scheduler',struct('GotoTag','SchedulerStatus')), ...
    reorg.wire('#scheduler.y1','#extra.u4','Scheduler'), ...
    reorg.wire([rawBus '.y1'],[packer '.u1'],'RawSensors'), ...
    reorg.wire([estimateBus '.y1'],[packer '.u2'],'Estimates'), ...
    reorg.wire([commandBus '.y1'],[packer '.u3'],'Commands'), ...
    reorg.wire('#extra.y1',[packer '.u4'],'ExtraSensors'), ...
    reorg.configure('blk_3304',struct('MaskDisplay', ...
        "disp('50 Hz ロギング：通常データ・指令補足・センサー補足\nOptical Flowの400 Hz差分は20 ms区間合計も保存。磁気は更新回数/経過時間を保存。\n制御処理は変更せず、補足フレームは同一の連番・時刻で対応付けます。')"))}];
reorg.edit(model,scope,ops);
reorg.edit(model,'root',{ ...
    reorg.wire([report.FlowID '.y1'],'blk_2963.u1','OpticalFlow'), ...
    reorg.wire([report.MagID '.y1'],'blk_2963.u2','MagneticField'), ...
    reorg.configure('blk_2963',icon('データロガー','50 Hz / 指令・全計測値',[530 1350 850 1515]))});
model_read(model,scope,'0');disp(model_check(model,scope,'["all"]'));
disp(model_check(model,'root','["all"]'));save_system(model);
report.Model=model;report.BaseRate=400;report.FlowPollRate=400;report.MagODR=30;
report.LogRate=50;report.FrameBytes=[190 190 246];report.ControlChanged=false;
save(fullfile(root,'build','tests','logging','model_setup.mat'),'report');
fprintf('EXTENDED_LOGGING_MODEL_READY\n');
end

function sensor(model,scope,system,fields,explanation)
[~,out]=reorg.ports(model,scope);
existing=find_system(reorg.path(model,scope),'SearchDepth',1,'Name','DeviceRead');
if isempty(existing)
ops={reorg.add('MATLABSystem','DeviceRead','device',struct('System',system)), ...
    reorg.add('BusCreator','SensorDataBus','bus',struct('Inputs',num2str(numel(fields))))};
for k=1:numel(fields),ops{end+1}=reorg.wire(sprintf('#device.y%d',k),sprintf('#bus.u%d',k),fields{k});end
ops{end+1}=reorg.wire('#bus.y1',[out{1} '.u1'],'SensorData');
reply=reorg.edit(model,scope,ops,'full');device=reorg.created(reply,'device');
else
device=reorg.id(existing{1});
end
reorg.edit(model,scope,{reorg.configure(device,struct('SampleTime','.0025'))});
if isempty(find_system(reorg.path(model,scope),'SearchDepth',1,'Name','JapaneseExplanation'))
    reorg.note(model,scope,explanation,[30 20 840 100]);
end
model_read(model,scope,'0');disp(model_check(model,scope,'["all"]'));
end

function tapCorrection(model)
if isempty(find_system(reorg.path(model,'blk_2721'),'SearchDepth',1,'Name','PublishFilteredAcceleration'))
reorg.edit(model,'blk_2721',{ ...
    reorg.add('Goto','PublishFilteredAcceleration','acc',struct('GotoTag','FilteredAcceleration','TagVisibility','global')), ...
    reorg.wire('blk_2921.y1','#acc.u1','FilteredAccelG')});
end
if isempty(find_system(reorg.path(model,'blk_3198'),'SearchDepth',1,'Name','PublishJoystickPilot'))
reorg.edit(model,'blk_3198',{ ...
    reorg.add('Goto','PublishJoystickPilot','pilot',struct('GotoTag','JoystickPilot','TagVisibility','global')), ...
    reorg.wire('blk_3202.y1','#pilot.u1','JoystickCommand')});
end
end

function [ops,bus]=fromBus(ops,rows,name,additional)
if nargin<4,additional=0;end
ref=[name 'Bus'];bus=['#' ref];
ops{end+1}=reorg.add('BusCreator',ref,ref,struct('Inputs',num2str(size(rows,1)+additional)));
for k=1:size(rows,1)
    ref=[name num2str(k)];
    ops{end+1}=reorg.add('From',['Read' rows{k,1}],ref,struct('GotoTag',rows{k,1}));
    ops{end+1}=reorg.wire(['#' ref '.y1'],sprintf('%s.u%d',bus,k),rows{k,2});
end
end

function p=icon(label,detail,position)
p=struct('Mask','on','MaskDisplay',sprintf('disp(''%s\\n%s'')',label,detail), ...
    'MaskIconOpaque','opaque','Position',position,'FontSize','11','BackgroundColor','white');
end
