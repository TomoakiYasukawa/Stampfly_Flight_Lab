function result=add_tof_tilt_kalman400(modelFile)
%ADD_TOF_TILT_KALMAN400 ToFを鉛直高さへ補正して既存の高度Kalmanへ渡す。
% Quaternionの正規化二乗を使い、400 Hzで三角関数を追加しない。
% PID・Madgwick・Kalman本体は変更しない。構造編集はSATK経由。
root=stampfly_project_root();model='StampFly_PIDBlock_FlightTest400';
if nargin<1,modelFile=fullfile(root,[model '.slx']);end
ensure_simulink_toolkit();assert(library.settingsLookup().gatePass);
open_system(modelFile);init_official();scope='blk_2231';
model_read(model,scope,'0');
existing=find_system(reorg.path(model,scope),'SearchDepth',1,'Name','ToFVerticalProjection400');
if isempty(existing)
    reply=reorg.edit(model,scope,{struct('op','create_subsystem', ...
        'name','ToFVerticalProjection400','ref','projection', ...
        'interface',struct('inputs',{{'SlantRangeM','QuaternionWXYZ','ParkingReset'}}, ...
        'outputs',{{'VerticalToFHeightM','DownProjection','ProjectionValid'}}))});
    result.ID=reorg.created(reply,'projection');
    [ins,outs]=reorg.ports(model,result.ID);
    ops={ ...
        reorg.add('Math','QuaternionSquared','square',struct('Operator','square')), ...
        reorg.add('Sum of Elements','QuaternionNormSquared','norm',struct), ...
        reorg.add('Selector','TiltQuaternionComponents','tilt',struct('InputPortWidth','4','Indices','[2 3]')), ...
        reorg.add('Sum of Elements','TiltSquaredSum','sumTilt',struct), ...
        reorg.add('Gain','TwiceTiltSquared','twice',struct('Gain','single(2)')), ...
        reorg.add('Saturation','NonzeroNormSquared','denominator',struct('LowerLimit','single(1e-8)','UpperLimit','single(inf)')), ...
        reorg.add('Product','NormalizedTiltSquared','divide',struct('Inputs','*/')), ...
        reorg.add('Constant','UnitProjection','one',struct('Value','single(1)')), ...
        reorg.add('Sum','DownwardProjection','projection',struct('Inputs','+-')), ...
        reorg.add('Saturation','BoundedProjection','bounded',struct('LowerLimit','single(0)','UpperLimit','single(1)')), ...
        reorg.add('Product','RangeTimesProjection','height',struct('Inputs','**')), ...
        reorg.add('Compare To Constant','SufficientDownProjection','downOK',struct('relop','>=','const','single(.5)')), ...
        reorg.add('Compare To Constant','FiniteProjection','projectionOK',struct('relop','<=','const','single(1.000001)')), ...
        reorg.add('Compare To Constant','NonzeroQuaternion','normOK',struct('relop','>','const','single(1e-8)')), ...
        reorg.add('Compare To Constant','NonnegativeRange','rangeOK',struct('relop','>=','const','single(0)')), ...
        reorg.add('Compare To Constant','FiniteSensorRange','finiteRange',struct('relop','<=','const','single(32.767)')), ...
        reorg.add('Logic','AttitudeValid','attitudeValid',struct('Operator','AND','Inputs','3')), ...
        reorg.add('Logic','RangeValid','rangeValid',struct('Operator','AND','Inputs','2')), ...
        reorg.add('Logic','MeasurementValid','valid',struct('Operator','AND','Inputs','2')), ...
        reorg.add('UnitDelay','PreviousVerticalHeight','previous',struct('SampleTime','.0025','InitialCondition','single(0)')), ...
        reorg.add('Constant','ResetHeight','zero',struct('Value','single(0)')), ...
        reorg.add('Switch','ResetPreviousHeight','reset',struct('Criteria','u2 ~= 0')), ...
        reorg.add('Switch','UseValidHeightOrHold','hold',struct('Criteria','u2 ~= 0')), ...
        reorg.wire([ins{2} '.y1'],'#square.u1','QuaternionWXYZ'), ...
        reorg.wire('#square.y1','#norm.u1','QuaternionSquared'), ...
        reorg.wire('#square.y1','#tilt.u1','QuaternionSquared'), ...
        reorg.wire('#tilt.y1','#sumTilt.u1','TiltSquared'), ...
        reorg.wire('#sumTilt.y1','#twice.u1','TiltSquaredSum'), ...
        reorg.wire('#norm.y1','#denominator.u1','QuaternionNormSquared'), ...
        reorg.wire('#twice.y1','#divide.u1','TwiceTiltSquared'), ...
        reorg.wire('#denominator.y1','#divide.u2','NormSquared'), ...
        reorg.wire('#one.y1','#projection.u1'), ...
        reorg.wire('#divide.y1','#projection.u2','NormalizedTiltSquared'), ...
        reorg.wire('#projection.y1','#bounded.u1','DownProjection'), ...
        reorg.wire('#bounded.y1','#height.u2','DownProjection'), ...
        reorg.wire([ins{1} '.y1'],'#height.u1','SlantRangeM'), ...
        reorg.wire('#projection.y1','#downOK.u1'), ...
        reorg.wire('#projection.y1','#projectionOK.u1'), ...
        reorg.wire('#norm.y1','#normOK.u1'), ...
        reorg.wire([ins{1} '.y1'],'#rangeOK.u1'), ...
        reorg.wire([ins{1} '.y1'],'#finiteRange.u1'), ...
        reorg.wire('#downOK.y1','#attitudeValid.u1'), ...
        reorg.wire('#projectionOK.y1','#attitudeValid.u2'), ...
        reorg.wire('#normOK.y1','#attitudeValid.u3'), ...
        reorg.wire('#rangeOK.y1','#rangeValid.u1'), ...
        reorg.wire('#finiteRange.y1','#rangeValid.u2'), ...
        reorg.wire('#attitudeValid.y1','#valid.u1'), ...
        reorg.wire('#rangeValid.y1','#valid.u2'), ...
        reorg.wire('#zero.y1','#reset.u1'), ...
        reorg.wire([ins{3} '.y1'],'#reset.u2','ParkingReset'), ...
        reorg.wire('#previous.y1','#reset.u3'), ...
        reorg.wire('#height.y1','#hold.u1','ProjectedHeightM'), ...
        reorg.wire('#valid.y1','#hold.u2','ProjectionValid'), ...
        reorg.wire('#reset.y1','#hold.u3','PreviousHeightM'), ...
        reorg.wire('#hold.y1','#previous.u1','VerticalToFHeightM'), ...
        reorg.wire('#hold.y1',[outs{1} '.u1'],'VerticalToFHeightM'), ...
        reorg.wire('#bounded.y1',[outs{2} '.u1'],'DownProjection'), ...
        reorg.wire('#valid.y1',[outs{3} '.u1'],'ProjectionValid')};
    reorg.edit(model,result.ID,ops,'full');
    reorg.note(model,result.ID,sprintf(['ToFの傾き補正（400 Hz）\n' ...
        '高さ = 斜距離 × 下向き投影係数。係数はQuaternionから計算し、水平なら1です。\n' ...
        '平らな床を仮定。下向き投影が0.5未満（傾き60度超）、姿勢・距離が無効な間は直前の高さを保持。\n' ...
        '補正した高さを既存Kalmanへ渡します。Kalmanの加速度入力とPIDゲインは元のままです。']),[20 20 1200 160]);
else
    result.ID=reorg.id(existing{1});
end
reorg.edit(model,scope,{ ...
    reorg.wire('blk_2242.y2',[result.ID '.u1'],'FilteredSlantRangeM'), ...
    reorg.wire('blk_2257.y1',[result.ID '.u2'],'QuaternionWXYZ'), ...
    reorg.wire('blk_2240.y5',[result.ID '.u3'],'ParkingReset'), ...
    reorg.wire([result.ID '.y1'],'blk_2236.u1','VerticalToFHeightM'), ...
    reorg.wire([result.ID '.y1'],'blk_2244.u3','VerticalToFHeightM'), ...
    reorg.add('Goto','PublishToFDownProjection','publishProjection',struct('GotoTag','ToFDownProjection','TagVisibility','global')), ...
    reorg.add('Goto','PublishToFProjectionValid','publishValid',struct('GotoTag','ToFProjectionValid','TagVisibility','global')), ...
    reorg.wire([result.ID '.y2'],'#publishProjection.u1','ToFDownProjection'), ...
    reorg.wire([result.ID '.y3'],'#publishValid.u1','ToFProjectionValid'), ...
    reorg.configure(result.ID,struct('Mask','on','MaskDisplay','disp(''ToF傾き補正\n鉛直高さ → Kalman / 400 Hz'')','FontSize','11')), ...
    reorg.configure('blk_3297',struct('Description',sprintf('姿勢・高度推定 400 Hz。Madgwick姿勢でToFを鉛直高さへ補正し、既存Kalmanで高度・速度を推定。光学フローは表示・記録専用。'), ...
        'MaskDisplay','disp(''姿勢・高度推定 400 Hz\nMadgwick → ToF鉛直補正 → 高度Kalman\nOptical Flowは表示・記録専用'')'))});
reorg.edit(model,'blk_2963',{reorg.configure('blk_3995',struct('FirmwareRevision','uint32(1503)'))});
disp(model_check(model,result.ID,'["all"]'));disp(model_check(model,scope,'["all"]'));
save_system(model,[],'OverwriteIfChangedOnDisk',true);
result.Model=model;result.ControlHz=400;result.Algorithm='range*(1-2*(qx^2+qy^2)/(qw^2+qx^2+qy^2+qz^2))';
result.MinDownProjection=.5;result.KalmanAlgorithmChanged=false;
save(fullfile(root,'build','tests','logging','tof_tilt_setup.mat'),'result');
fprintf('TOF_TILT_KALMAN_MODEL_READY\n');
end
