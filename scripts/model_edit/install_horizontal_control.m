function report=install_horizontal_control()
%INSTALL_HORIZONTAL_CONTROL 現行モデルへ水平推定・速度制御を追加する。
% 既存7 PID、Stateflow、推力・配分・通信条件は保持します。
root=stampfly_project_root();ensure_simulink_toolkit();assert(library.settingsLookup().gatePass);
init_imu_flight();m='StampFly_IMU400';open_system(fullfile(root,[m '.slx']));
folder=fullfile(root,'build','horizontal_control');if ~isfolder(folder),mkdir(folder);end
checkpoint=fullfile(folder,'installation.mat');
assert(~isfile(checkpoint),'horizontal:Installed','Installation already saved; inspect the checkpoint before editing.');
baseline=fullfile(root,'archive','snapshots','HorizontalBaseline.slx');assert(isfile(baseline));
assert(numel(find_system(m,'LookUnderMasks','all','Name','DedicatedPID'))==7);
% 1. 最上位に「水平推定」を置き、関連データは名前付きバスで渡します。
reply=reorg.edit(m,'root',{struct('op','create_subsystem','name','HorizontalMotionEstimation','ref','estimator', ...
    'interface',struct('inputs',{{'OpticalFlow','Attitude','RawIMU','FilteredIMU','Calibration','BottomRange','VerticalMotion','Context'}}, ...
    'outputs',{{'HorizontalMotion'}}))},'incremental');
estimator=reorg.created(reply,'estimator');[inputs,outputs]=reorg.ports(m,estimator);
ops={reorg.add('BusSelector','FlowFields','flowFields',struct('OutputSignals','Delta,Raw,Info,Totals')), ...
    reorg.add('BusCreator','OpticalFlowBus','flowBus',struct('Inputs','4','OutDataTypeStr','Bus: HorizontalFlowBus','NonVirtualBus','on','InheritFromInputs','off')), ...
    reorg.add('BusSelector','AttitudeFields','att',struct('OutputSignals','Quaternion,AngularRate')), ...
    reorg.add('BusSelector','RawIMUFields','raw',struct('OutputSignals','AngularRate')), ...
    reorg.add('BusSelector','FilteredIMUFields','filtered',struct('OutputSignals','AngularRate')), ...
    reorg.add('BusSelector','CalibrationFields','cal',struct('OutputSignals','Offsets')), ...
    reorg.add('BusSelector','BottomRangeFields','range',struct('OutputSignals','DistanceMm,Fresh')), ...
    reorg.add('BusSelector','VerticalMotionFields','vertical',struct('OutputSignals','Velocity')), ...
    reorg.add('From','ReadIMUFresh','imuFresh',struct('GotoTag','IMUSampleFresh')), ...
    reorg.add('From','ReadRangeStatus','rangeStatus',struct('GotoTag','BottomRangeStatus')), ...
    reorg.add('BusCreator','InertialMotionBus','imu',struct('Inputs','6','OutDataTypeStr','Bus: HorizontalInertialBus','NonVirtualBus','on','InheritFromInputs','off')), ...
    reorg.add('BusCreator','RangeMotionBus','rangeBus',struct('Inputs','4','OutDataTypeStr','Bus: HorizontalRangeBus','NonVirtualBus','on','InheritFromInputs','off')), ...
    reorg.add('MATLABSystem','FlowMotion','tracker',struct('System','horizontal.FlowMotion')), ...
    reorg.add('BusCreator','HorizontalMotionBus','motionBus',struct('Inputs','6','OutDataTypeStr','Bus: HorizontalMotionBus','NonVirtualBus','on','InheritFromInputs','off'))};
selectRefs={'att','raw','filtered','cal','range','vertical'};
for k=1:6,ops{end+1}=reorg.wire([inputs{k+1} '.y1'],['#' selectRefs{k} '.u1']);end %#ok<AGROW>
imuFeeds={'#att.y1','#raw.y1','#cal.y1','#filtered.y1','#att.y2','#imuFresh.y1'};
imuNames={'Quaternion','RawAngularRate','StaticOffsets','FilteredRate','CorrectedRate','Fresh'};
for k=1:6,ops{end+1}=reorg.wire(imuFeeds{k},sprintf('#imu.u%d',k),imuNames{k});end %#ok<AGROW>
rangeFeeds={'#range.y1','#range.y2','#rangeStatus.y1','#vertical.y1'};
rangeNames={'DistanceMm','Fresh','Status','VerticalSpeed'};
for k=1:4,ops{end+1}=reorg.wire(rangeFeeds{k},sprintf('#rangeBus.u%d',k),rangeNames{k});end %#ok<AGROW>
ops{end+1}=reorg.wire([inputs{1} '.y1'],'#flowFields.u1');
flowNames={'Delta','Raw','Info','Totals'};
for k=1:4,ops{end+1}=reorg.wire(sprintf('#flowFields.y%d',k),sprintf('#flowBus.u%d',k),flowNames{k});end %#ok<AGROW>
ops=[ops {reorg.wire('#flowBus.y1','#tracker.u1'),reorg.wire('#imu.y1','#tracker.u2'), ...
    reorg.wire('#rangeBus.y1','#tracker.u3'),reorg.wire([inputs{8} '.y1'],'#tracker.u4')}];
motionNames={'Position','Velocity','Heading','Height','Status','Diagnostics'};
for k=1:6,ops{end+1}=reorg.wire(sprintf('#tracker.y%d',k),sprintf('#motionBus.u%d',k),motionNames{k});end %#ok<AGROW>
ops{end+1}=reorg.wire('#motionBus.y1',[outputs{1} '.u1'],'HorizontalMotion');
reorg.edit(m,estimator,ops,'full');verifyScope(m,estimator);
% 2. 姿勢リセットは推定基準も取り直します。待機から連続して推定します。
ops={reorg.add('BusCreator','HorizontalContextBus','ctx',struct('Inputs','3','OutDataTypeStr','Bus: HorizontalContextBus','NonVirtualBus','on','InheritFromInputs','off')), ...
    reorg.add('RelationalOperator','HorizontalPoseReady','ready',struct('Operator','>')), ...
    reorg.add('Constant','CalibrationMode','calMode',struct('Value','uint8(1)')), ...
    reorg.wire('blk_4169.y1','#ctx.u1','Dt'),reorg.wire('blk_4166.y3','#ctx.u2','AttitudeReset'), ...
    reorg.wire('blk_4166.y2','#ready.u1'),reorg.wire('#calMode.y1','#ready.u2'), ...
    reorg.wire('#ready.y1','#ctx.u3','PoseReady'), ...
    reorg.wire('blk_3979.y1',[estimator '.u1'],'OpticalFlow'), ...
    reorg.wire('blk_2231.y1',[estimator '.u2'],'Attitude'), ...
    reorg.wire('blk_3161.y1',[estimator '.u3'],'RawIMU'), ...
    reorg.wire('blk_2721.y1',[estimator '.u4'],'FilteredIMU'), ...
    reorg.wire('blk_2721.y3',[estimator '.u5'],'Calibration'), ...
    reorg.wire('blk_3178.y1',[estimator '.u6'],'BottomRange'), ...
    reorg.wire('blk_2231.y2',[estimator '.u7'],'VerticalMotion'),reorg.wire('#ctx.y1',[estimator '.u8'],'Context')};
reorg.edit(m,'root',ops,'incremental');
% 3. 水平情報を制御の各境界へ追加し、既存の入力端子は移動しません。
reply=reorg.edit(m,'blk_2274',{reorg.add('Inport','HorizontalMotion','motion',struct('Port','5','OutDataTypeStr','Bus: HorizontalMotionBus'))});
flightMotion=reorg.created(reply,'motion');
reply=reorg.edit(m,'blk_2297',{reorg.add('Inport','HorizontalMotion','motion',struct('Port','5','OutDataTypeStr','Bus: HorizontalMotionBus')), ...
    reorg.add('BusSelector','PreviousSaturationFields','satFields',struct('OutputSignals','Duty')), ...
    reorg.add('Constant','MotorDutyBounds','dutyBounds',struct('Value','single([0;.95])')), ...
    reorg.add('RelationalOperator','MotorSaturationHigh','high',struct('Operator','>=')), ...
    reorg.add('RelationalOperator','MotorSaturationLow','low',struct('Operator','<=')), ...
    reorg.add('Constant','HighDutyBound','highBound',struct('Value','single(.95)')), ...
    reorg.add('Constant','LowDutyBound','lowBound',struct('Value','single(0)')), ...
    reorg.add('Logic','SaturatedMotorVector','satVector',struct('Operator','OR','Inputs','2')), ...
    reorg.add('Logic','AnyMotorSaturation','satAny',struct('Operator','OR','Inputs','1')), ...
    reorg.add('UnitDelay','PreviousMotorSaturation','satDelay',struct('SampleTime','Official.Step','InitialCondition','false')), ...
    reorg.wire('blk_3674.y1','#satFields.u1'),reorg.wire('#satFields.y1','#high.u1'), ...
    reorg.wire('#highBound.y1','#high.u2'),reorg.wire('#satFields.y1','#low.u1'), ...
    reorg.wire('#lowBound.y1','#low.u2'),reorg.wire('#high.y1','#satVector.u1'), ...
    reorg.wire('#low.y1','#satVector.u2'),reorg.wire('#satVector.y1','#satAny.u1'), ...
    reorg.wire('#satAny.y1','#satDelay.u1')});
takeoffMotion=reorg.created(reply,'motion');saturation=reorg.created(reply,'satDelay');
% 削除：上限・下限は個別定数を用い、不要なベクトル定数を残しません。
reorg.edit(m,'blk_2297',{struct('op','delete','target',reorg.created(reply,'dutyBounds'))});
reorg.edit(m,'blk_2297',{reorg.configure(reorg.created(reply,'high'),struct('Operator','>=')), ...
    reorg.configure(reorg.created(reply,'low'),struct('Operator','<='))});
reply=reorg.edit(m,'blk_3421',{reorg.add('Inport','HorizontalMotion','motion',struct('Port','4','OutDataTypeStr','Bus: HorizontalMotionBus')), ...
    reorg.add('Inport','PreviousMotorSaturation','saturation',struct('Port','5','OutDataTypeStr','boolean')), ...
    struct('op','create_subsystem','name','HorizontalControl','ref','controller', ...
    'interface',struct('inputs',{{'HorizontalMotion','ManualAngleRP','SharedControlContext','PreviousMotorSaturation'}}, ...
    'outputs',{{'SelectedAngleRP','Diagnostics24'}}))});
attitudeMotion=reorg.created(reply,'motion');attitudeSaturation=reorg.created(reply,'saturation');controller=reorg.created(reply,'controller');
[ci,co]=reorg.ports(m,controller);
% 4. 教材として読みやすい3処理を並べます。速度目標の生成とPIの境界を分けます。
ops={reorg.add('MATLABSystem','Command','cmd',struct('System','horizontal.Command')), ...
    reorg.add('MATLABSystem','VelocityPI','pi',struct('System','horizontal.VelocityPI')), ...
    reorg.add('MATLABSystem','SelectAttitude','select',struct('System','horizontal.SelectAttitude')), ...
    reorg.add('BusSelector','MotionLogFields','fields',struct('OutputSignals','Position,Velocity,Heading,Height,Status')), ...
    reorg.add('DataTypeConversion','StateToSingle','stateSingle',struct('OutDataTypeStr','single')), ...
    reorg.add('DataTypeConversion','EnabledToSingle','enabledSingle',struct('OutDataTypeStr','single')), ...
    reorg.add('DataTypeConversion','SaturationToSingle','satSingle',struct('OutDataTypeStr','single')), ...
    reorg.add('Terminator','AssistAngleDiagnostic','unusedAssist'), ...
    reorg.add('Selector','ValidityForControlLog','validity',struct('NumberOfDimensions','1','IndexMode','One-based', ...
        'InputPortWidth','8','IndexOptionArray',{{'Index vector (dialog)'}},'IndexParamArray',{{'[1 4 5 7]'}})), ...
    reorg.add('Mux','PackHorizontalDiagnostics','diag',struct('Inputs','14'))};
ops=[ops {reorg.wire([ci{1} '.y1'],'#cmd.u1'),reorg.wire([ci{2} '.y1'],'#cmd.u2'), ...
    reorg.wire([ci{3} '.y1'],'#cmd.u3'),reorg.wire('#cmd.y1','#pi.u1'), ...
    reorg.wire([ci{1} '.y1'],'#pi.u2'),reorg.wire('#cmd.y2','#pi.u3'),reorg.wire([ci{4} '.y1'],'#pi.u4'), ...
    reorg.wire([ci{2} '.y1'],'#select.u1'),reorg.wire('#pi.y1','#select.u2'), ...
    reorg.wire([ci{1} '.y1'],'#select.u3'),reorg.wire('#cmd.y2','#select.u4'), ...
    reorg.wire([ci{3} '.y1'],'#select.u5'),reorg.wire('#select.y1',[co{1} '.u1'],'SelectedAngleRP'), ...
    reorg.wire([ci{1} '.y1'],'#fields.u1'),reorg.wire('#cmd.y3','#stateSingle.u1'), ...
    reorg.wire('#cmd.y2','#enabledSingle.u1'),reorg.wire('#pi.y3','#satSingle.u1'), ...
    reorg.wire('#fields.y5','#validity.u1'),reorg.wire('#select.y3','#unusedAssist.u1')}];
diagFeeds={'#fields.y1','#fields.y2','#cmd.y1','#cmd.y4','#pi.y1','#pi.y2', ...
    '#select.y1','#select.y2','#stateSingle.y1','#enabledSingle.y1','#satSingle.y1','#fields.y4','#fields.y3','#validity.y1'};
for k=1:numel(diagFeeds),ops{end+1}=reorg.wire(diagFeeds{k},sprintf('#diag.u%d',k));end %#ok<AGROW>
ops{end+1}=reorg.wire('#diag.y1',[co{2} '.u1'],'Diagnostics24');
reply=reorg.edit(m,controller,ops,'full');command=reorg.created(reply,'cmd');
% MATLABSystemへ渡す混合型条件は、必要な項目だけの非仮想バスへ変換します。
reorg.edit(m,controller,{ ...
    reorg.add('BusSelector','HorizontalContextFields','contextFields',struct('OutputSignals', ...
        'Dt,ControlMode,FlightContext.Branch,ControlContext.Run,ControlContext.Reset,ControlContext.AltitudeEnabled')), ...
    reorg.add('DataTypeConversion','ControlModeToUint8','controlMode',struct('OutDataTypeStr','uint8')), ...
    reorg.add('BusCreator','HorizontalFlightContext','flight',struct('Inputs','1', ...
        'OutDataTypeStr','Bus: HorizontalFlightContextBus','NonVirtualBus','on','InheritFromInputs','off')), ...
    reorg.add('BusCreator','HorizontalControlGates','gates',struct('Inputs','3', ...
        'OutDataTypeStr','Bus: HorizontalControlGatesBus','NonVirtualBus','on','InheritFromInputs','off')), ...
    reorg.add('BusCreator','HorizontalControlContext','context',struct('Inputs','4', ...
        'OutDataTypeStr','Bus: HorizontalControlContextBus','NonVirtualBus','on','InheritFromInputs','off')), ...
    reorg.wire([ci{3} '.y1'],'#contextFields.u1'),reorg.wire('#contextFields.y1','#context.u1'), ...
    reorg.wire('#contextFields.y2','#controlMode.u1'),reorg.wire('#controlMode.y1','#context.u2'), ...
    reorg.wire('#contextFields.y3','#flight.u1'),reorg.wire('#flight.y1','#context.u3'), ...
    reorg.wire('#contextFields.y4','#gates.u1'),reorg.wire('#contextFields.y5','#gates.u2'), ...
    reorg.wire('#contextFields.y6','#gates.u3'),reorg.wire('#gates.y1','#context.u4'), ...
    reorg.wire('#context.y1',[command '.u3']),reorg.wire('#context.y1',[reorg.created(reply,'select') '.u5'])});
% 24値に合わせ、観測有効性・棄却理由はMotion.Statusを別ログで保持します。
verifyScope(m,controller);
% 5. 既存の角度目標を差し替えます。YawとPID内部の演算・係数は変更しません。
reorg.edit(m,'blk_3421',{reorg.wire([attitudeMotion '.y1'],[controller '.u1']), ...
    reorg.wire('blk_3429.y1',[controller '.u2'],'ManualAngleRP'), ...
    reorg.wire('blk_3426.y1',[controller '.u3'],'SharedControlContext'), ...
    reorg.wire([attitudeSaturation '.y1'],[controller '.u4']), ...
    reorg.wire([controller '.y1'],'blk_3430.u1','AngleReference'), ...
    reorg.wire([controller '.y1'],'blk_3428.u1','AngleReference'), ...
    reorg.add('Goto','PublishHorizontalControl','controlLog',struct('GotoTag','HorizontalControlDiagnostics','TagVisibility','global')), ...
    reorg.wire([controller '.y2'],'#controlLog.u1','HorizontalControlDiagnostics')});
reorg.edit(m,'blk_2297',{reorg.wire([takeoffMotion '.y1'],'blk_3421.u4','HorizontalMotion'), ...
    reorg.wire([saturation '.y1'],'blk_3421.u5','PreviousMotorSaturation')});
reorg.edit(m,'blk_2274',{reorg.wire([flightMotion '.y1'],'blk_2297.u5','HorizontalMotion')});
reorg.edit(m,'root',{reorg.wire([estimator '.y1'],'blk_2274.u5','HorizontalMotion'), ...
    reorg.add('Goto','PublishHorizontalMotion','motionLog',struct('GotoTag','HorizontalMotion','TagVisibility','global')), ...
    reorg.wire([estimator '.y1'],'#motionLog.u1','HorizontalMotion')});
% 50 Hzログへは名前付きFromで渡します。既存の3パケットを保持します。
reorg.edit(m,'blk_2963',{ ...
    reorg.add('From','ReadHorizontalMotion','motionLog',struct('GotoTag','HorizontalMotion')), ...
    reorg.add('From','ReadHorizontalControl','controlLog',struct('GotoTag','HorizontalControlDiagnostics')), ...
    reorg.add('MATLABSystem','HorizontalLogger50','horizontalLog',struct('System','horizontal.Logger')), ...
    reorg.add('Terminator','HorizontalFrameSent','frameSent'), ...
    reorg.wire('blk_4001.y1','#horizontalLog.u1'),reorg.wire('#controlLog.y1','#horizontalLog.u2'), ...
    reorg.wire('#motionLog.y1','#horizontalLog.u3'),reorg.wire('#horizontalLog.y1','#frameSent.u1')});
for scope={controller,estimator,'blk_3421','blk_2297','blk_2274','root'},verifyScope(m,scope{1});end
% 配線済みの状態を保存しておき、検証で問題があればこの状態から修正します。
save_system(m);
% 6. 全新規ブロックに説明を付け、端子名を表示して保存します。
decorate(m,estimator,'水平推定：フロー・時間と同一区間の角速度積分、ToFの傾き補正、品質・鮮度の評価。局所X=基準機首、Y=右。');
decorate(m,controller,'水平制御：移動/減速/保持の目標生成→速度PI→姿勢目標選択。既存7 PIDの前段に接続。');
logger=find_system(m,'LookUnderMasks','all','BlockType','MATLABSystem','System','basic.ExtendedLogger50');
assert(isscalar(logger));reorg.edit(m,reorg.id(get_param(logger{1},'Parent')),{reorg.configure(reorg.id(logger{1}),struct('FirmwareRevision','uint32(1801)'))});
set_param(m,'SimulationCommand','update');
assert(numel(find_system(m,'LookUnderMasks','all','Name','DedicatedPID'))==7);
save_system(m);
report=struct('Model',[m '.slx'],'Estimator',estimator,'Controller',controller,'Command',command, ...
    'PreviousMotorSaturation',saturation,'FlightMotionInput',flightMotion,'TakeoffMotionInput',takeoffMotion, ...
    'AttitudeMotionInput',attitudeMotion,'AttitudeSaturationInput',attitudeSaturation, ...
    'FirmwareRevision',1801,'PIDCount',7,'PhysicalFlightTested',false);
save(checkpoint,'report');writeJSON(fullfile(root,'docs','horizontal_control_structure.json'),report);
fprintf('HORIZONTAL_CONTROL_INSTALLED_AND_UPDATED\n');
end
function verifyScope(m,scope)
disp(model_read(m,scope,'0'));text=char(model_check(m,scope,'["all"]'));disp(text);
assert(~contains(text,'severity: error')&&~contains(text,'status: error'),'horizontal:Connectivity','%s',text);
end
function decorate(m,id,description)
p=reorg.path(m,id);[inputs,outputs]=reorg.ports(m,id);
display=char(sprintf("disp('%s');",get_param(p,'Name')));
for k=1:numel(inputs),display=[display char(sprintf("port_label('input',%d,'%s');",k,get_param(reorg.path(m,inputs{k}),'Name')))];end %#ok<AGROW>
for k=1:numel(outputs),display=[display char(sprintf("port_label('output',%d,'%s');",k,get_param(reorg.path(m,outputs{k}),'Name')))];end %#ok<AGROW>
parent=get_param(p,'Parent');scope='root';if ~strcmp(parent,m),scope=reorg.id(parent);end
reorg.edit(m,scope,{reorg.configure(id,struct('Description',description, ...
    'Mask','on','MaskDescription',description,'ShowName','off','ShowPortLabels','FromPortBlockName'))});
reorg.edit(m,scope,{reorg.configure(id,struct('MaskDisplay',display))});
children=find_system(p,'SearchDepth',1,'Type','Block');ops={};
for k=1:numel(children)
    b=children{k};if strcmp(b,p),continue;end
    if strcmp(get_param(b,'BlockType'),'MATLABSystem'),continue;end
    ops{end+1}=reorg.configure(reorg.id(b),struct('Description',[get_param(b,'Name') '：水平推定・制御の名前付きデータを選択・結合・接続します。信号の2軸順を保持します。'])); %#ok<AGROW>
end
if ~isempty(ops),reorg.edit(m,id,ops);end
end
function writeJSON(file,value)
fid=fopen(file,'w','n','UTF-8');assert(fid>=0);fprintf(fid,'%s\n',jsonencode(value,'PrettyPrint',true));fclose(fid);
end
