function report=repair_vertical_boundary()
%REPAIR_VERTICAL_BOUNDARY 概要：高度推定の加速度単位と繰返しリセットを修正。
% MATLAB Functionの3状態推定と既存7 PIDは維持し、入口と診断の単位をそろえます。
root=stampfly_project_root();ensure_simulink_toolkit();assert(library.settingsLookup().gatePass);
init_imu_flight();m='StampFly_IMU400';open_system(fullfile(root,[m '.slx']));
assert(strcmp(get_param(m,'Dirty'),'off'),'保存済みのモデルを使ってください。');
scope='blk_2231';disp(model_read(m,scope,'1'));
snapshot=fullfile(root,'archive','snapshots','Horizontal1801.slx');
if ~isfile(snapshot),copyfile(fullfile(root,[m '.slx']),snapshot);end
beforePID=pidParameters(m);
operations={ ...
    reorg.add('Gain','VerticalAccelGToMps2','accSI',struct('Gain','9.80665', ...
        'OutDataTypeStr','single','Description','鉛直加速度をgからm/s²へ換算します。高度[m]・速度[m/s]の予測に使うため、推定器入口で単位をそろえます。')),...
    reorg.add('UnitDelay','PreviousParkingReset','previousReset',struct('SampleTime','.0025', ...
        'InitialCondition','false','Description','前周期の待機リセット要求を記憶し、待機へ入る瞬間だけを検出します。')),...
    reorg.add('Logic','NotPreviousParkingReset','notReset',struct('Operator','NOT', ...
        'Description','前周期に待機リセットが要求されていなかったことを確認します。')),...
    reorg.add('Logic','ParkingResetEdge','resetEdge',struct('Operator','AND','Inputs','2', ...
        'Description','待機へ入る立上りだけでカルマン共分散を初期化します。待機中の毎周期リセットによる飛行切替直後の速度ジャンプを防ぎます。')),...
    reorg.add('Gain','KalmanBiasMps2ToG','biasG',struct('Gain','1/9.80665', ...
        'OutDataTypeStr','single','Description','推定器内の加速度バイアス[m/s²]を従来ログのgへ換算します。制御用の高度・速度には影響しません。')),...
    reorg.wire('blk_2242.y1','#accSI.u1','VerticalAccelG'), ...
    reorg.wire('#accSI.y1','blk_2236.u2','VerticalAccelMps2'), ...
    reorg.wire('blk_2240.y5','#previousReset.u1','ParkingResetRequest'), ...
    reorg.wire('#previousReset.y1','#notReset.u1'), ...
    reorg.wire('blk_2240.y5','#resetEdge.u1','ParkingResetRequest'), ...
    reorg.wire('#notReset.y1','#resetEdge.u2'), ...
    reorg.wire('#resetEdge.y1','blk_2236.u5','ParkingResetEdge'), ...
    reorg.wire('blk_2236.y3','#biasG.u1','KalmanBiasMps2'), ...
    reorg.wire('#biasG.y1','blk_2260.u1','KalmanBiasG'), ...
    reorg.configure('blk_2236',struct('Description', ...
        'ToF高さ[m]と鉛直加速度[m/s²]から[速度m/s;高度m;加速度バイアスm/s²]を推定するMATLAB Functionです。加速度のg換算と待機リセットの立上りは周囲のブロックで明示します。高度・速度は既存PIDへ直接渡します。'))};
reply=reorg.edit(m,scope,operations,'incremental');
set_param(m,'SimulationCommand','update');
assert(isequaln(beforePID,pidParameters(m)),'vertical:PIDChanged','既存のPID係数が変わりました。');
check=char(model_check(m,scope,'["unconnected_ports","unconnected_lines"]'));disp(check);
assert(~contains(check,'severity: error')&&~contains(check,'status: error'));
save_system(m);
report=struct('Passed',true,'Model',[m '.slx'],'AccelerationInputUnits','m/s^2', ...
    'BiasTelemetryUnits','g','ParkingReset','rising edge only', ...
    'PIDCount',7,'PIDParametersPreserved',true,'CoreEstimatorUnchanged',true, ...
    'PreviousSnapshot','archive/snapshots/Horizontal1801.slx', ...
    'AccelerationGain',reorg.created(reply,'accSI'),'ResetEdge',reorg.created(reply,'resetEdge'), ...
    'BiasConversion',reorg.created(reply,'biasG'),'Flashed',false,'FlightVerified',false);
fid=fopen(fullfile(root,'docs','vertical_boundary_repair.json'),'w','n','UTF-8');assert(fid>=0);
fprintf(fid,'%s\n',jsonencode(report,'PrettyPrint',true));fclose(fid);
fprintf('VERTICAL_BOUNDARY_REPAIR_SAVED\n');
end
function records=pidParameters(model)
blocks=find_system(model,'LookUnderMasks','all','Name','DedicatedPID');assert(numel(blocks)==7);
records=cell(size(blocks));
for k=1:numel(blocks)
    names=fieldnames(get_param(blocks{k},'DialogParameters'));values=struct;
    for j=1:numel(names),values.(names{j})=get_param(blocks{k},names{j});end
    records{k}=struct('ID',reorg.id(blocks{k}),'Parameters',values);
end
end
