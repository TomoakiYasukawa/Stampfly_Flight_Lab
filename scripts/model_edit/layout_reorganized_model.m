function params=icon(title,subtitle,position)
text=[title newline subtitle];text=char(strrep(strrep(text,"'","''"),newline,'\n'));
params=struct('Mask','on','MaskDisplay',['disp(''' text ''')'],'MaskIconOpaque','opaque','MaskIconFrame','on', ...
    'ShowPortLabels','FromPortBlockName','Position',position,'AttributesFormatString','','FontSize','11','BackgroundColor','white');
end
function desc=descriptionFor(name)
switch name
    case 'IMUFiltering',desc=sprintf('IMUフィルター（400 Hz）\n加速度・角速度のバイアス補正と低域フィルター。鉛直加速度の変化も出力。\n各軸のSum / Gain / Unit Delayを編集して、元の演算順を確認できます。');
    case 'IMUAxisConversion',desc='センサー座標から機体座標へ軸を入れ替え、符号と単位を変換します。姿勢推定・制御で同じ座標系を使うための処理です。';
    case 'VerticalAcceleration',desc='加速度Zの変化を公式と同じ低域フィルターで処理し、高度Kalmanへ渡す鉛直加速度を作ります。';
    case 'TakeoffHoverControl400',desc=sprintf('姿勢角 → 角速度、目標高度 → 鉛直速度の二重ループ。\nPID、指令選択、推力制限、モーター配分を個別ブロックで編集できます。\nTakeoffLandingCommandとFinalizeFlightModeだけが状態遷移図です。');
    otherwise,desc='推力と3軸トルクを4モーターへ配分。元のフィルター、Duty上限0.95、8 bit量子化を維持しています。';
end
end
function placeTags(model)
tags=[find_system(model,'BlockType','Goto');find_system(model,'BlockType','From')];scoped=struct;
for k=1:numel(tags)
    ports=get_param(tags{k},'PortHandles');parent=get_param(tags{k},'Parent');
    if strcmp(get_param(tags{k},'BlockType'),'Goto')
        line=get_param(ports.Inport,'Line');src=get_param(line,'SrcPortHandle');q=get_param(src,'Position');pos=[q(1)+35 q(2)-9 q(1)+230 q(2)+9];
    else
        line=get_param(ports.Outport,'Line');dst=get_param(line,'DstPortHandle');q=get_param(dst(1),'Position');pos=[q(1)-230 q(2)-9 q(1)-35 q(2)+9];
    end
    if strcmp(parent,model),scope='root';else,scope=reorg.id(parent);end
    if ~isfield(scoped,scope),scoped.(scope)={};end
    scoped.(scope){end+1}=reorg.configure(reorg.id(tags{k}),struct('Position',pos,'FontSize','9'));
end
scopes=fieldnames(scoped);for k=1:numel(scopes),reorg.edit(model,scopes{k},scoped.(scopes{k}));end
end
