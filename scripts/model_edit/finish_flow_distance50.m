function finish_flow_distance50()
%FINISH_FLOW_DISTANCE50 距離の50 Hz更新値を400 Hzログ入力へ保持して渡す。
model='StampFly_PIDBlock_FlightTest400';
reply=reorg.edit(model,'blk_2963',{ ...
    reorg.add('RateTransition','HoldFlowDistance400','holdDistance', ...
        struct('OutPortSampleTime','.0025')), ...
    reorg.wire('blk_4056.y1','#holdDistance.u1','Distance50Hz'), ...
    reorg.wire('#holdDistance.y1','blk_4034.u5','Distance')}); %#ok<NASGU>
reorg.edit(model,'root',{ ...
    reorg.configure('blk_3979',struct('MaskDisplay', ...
        "disp(sprintf('Optical Flow 取得\n400 Hz / 記録専用'))")), ...
    reorg.configure('blk_3983',struct('MaskDisplay', ...
        "disp(sprintf('磁気取得\n30 Hz / 最新値は400 Hz'))")), ...
    reorg.configure('blk_2963',struct('MaskDisplay', ...
        "disp(sprintf('データロガー\n50 Hz / 指令・全計測値'))")), ...
    reorg.configure('blk_4038',struct('MaskDisplay', ...
        "disp(sprintf('Flow移動距離 [m]\n50 Hz / 表示・記録専用'))"))});
disp(model_read(model,'blk_2963','0'));
disp(model_check(model,'root','["all"]'));
save_system(model,[],'OverwriteIfChangedOnDisk',true);
end
