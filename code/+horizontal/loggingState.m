function value=loggingState(kind)
%LOGGINGSTATE 概要：分散ロガーが保存する固定型・固定サイズの初期値。
% LogRawBus、LogEstimateBus、BasicLogCommandBus、LogExtraBusと一致します。
% 機器を読み出さず、50 Hzの同時刻の入力を後続周期へ保持するための状態です。
%#codegen
switch kind
    case 'raw'
        value=struct('Acceleration',zeros(3,1,'single'),'AngularRate',zeros(3,1,'single'), ...
            'IMUFresh',uint8(0),'Time',single(0),'BottomMm',int16(0),'ToFFresh',uint8(0), ...
            'ToFStatus',uint8(0),'Voltage',single(0),'BatteryValid',uint8(0), ...
            'ToFInfo',zeros(4,1,'uint32'),'Temperature',single(0));
    case 'estimate'
        value=struct('Angles',zeros(3,1,'single'),'Height',single(0),'Velocity',single(0), ...
            'ControlDiagnostics',zeros(17,1,'single'),'SensorDiagnostics',zeros(8,1,'single'), ...
            'FilteredAccel',zeros(3,1,'single'),'FilteredGyro',zeros(3,1,'single'), ...
            'Quaternion',zeros(4,1,'single'),'Flags',zeros(3,1,'uint8'));
    case 'control'
        pilot=struct('Sticks',zeros(6,1,'single'),'ArmButton',uint8(0), ...
            'NewPacket',uint8(0),'AHRSRequest',uint8(0));
        value=struct('Duty',zeros(4,1,'single'),'AppliedCounts',zeros(4,1,'uint8'), ...
            'PWMStatus',zeros(4,1,'uint32'),'PacketError',uint8(0),'Connected',uint8(0), ...
            'AltitudeEnabled',uint8(0),'PreviousMode',uint8(0),'Mode',uint8(0), ...
            'Dt',single(0),'StartUs',uint32(0),'UsedSticks',zeros(6,1,'single'), ...
            'Pilot',pilot,'OutputEnabled',false);
    case 'extra'
        flow=struct('Delta',zeros(2,1,'single'),'Raw',zeros(8,1,'uint16'), ...
            'Info',zeros(4,1,'uint32'),'Totals',zeros(2,1,'uint32'));
        mag=struct('Field',zeros(3,1,'single'),'Flags',zeros(3,1,'uint8'), ...
            'Info',zeros(6,1,'uint32'));
        distance=struct('PositionEN',zeros(2,1,'single'),'Used',uint8(0), ...
            'DeltaEN',zeros(2,1,'single'));
        value=struct('Flow',flow,'Mag',mag,'Timing',zeros(8,1,'uint32'), ...
            'Scheduler',zeros(4,1,'uint32'),'Distance',distance);
    otherwise
        error('horizontal:LoggingState','Unknown logging state.');
end
end
