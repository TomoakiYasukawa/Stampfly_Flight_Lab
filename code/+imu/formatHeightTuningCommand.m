function command = formatHeightTuningCommand(sequence,values)
%FORMATHEIGHTTUNINGCOMMAND Build the receiver's namespaced height request.
values = single(values(:));
[lower,upper] = imu.heightTuningLimits();
assert(numel(values) == 9 && all(isfinite(values)) && ...
    all(values >= lower) && all(values <= upper), ...
    'imu:InvalidHeightTuning','Height settings are outside the allowed range.');
assert(isscalar(sequence) && isfinite(double(sequence)) && ...
    sequence >= 0 && sequence <= 65535 && sequence == floor(double(sequence)), ...
    'imu:InvalidTuningSequence','Tuning sequence must be uint16.');
quantized = round(values.*imu.heightTuningScales());
assert(all(quantized <= 32767) && all(quantized >= 0), ...
    'imu:TuningQuantization','Height settings exceed the transport range.');
command = uint8(sprintf('TUNE,%u,1,9,%u,%u,%u,%u,%u,%u,%u,%u,%u\n', ...
    uint16(sequence),uint16(quantized)));
end
