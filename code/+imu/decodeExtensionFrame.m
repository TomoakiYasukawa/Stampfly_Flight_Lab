function sample=decodeExtensionFrame(frame)
%DECODEEXTENSIONFRAME CRC-check SFIX190 / SFIY246, independent of normal frames.
data=uint8(frame(:));
command=numel(data)==190 && isequal(data(1:4),uint8('SFIX').');
sensor=numel(data)==246 && isequal(data(1:4),uint8('SFIY').');
assert(command || sensor,'imu:InvalidExtension','Expected SFIX190 or SFIY246.');
assert(typecast(data(end-1:end),'uint16')==imu.crc16(data(1:end-2)), ...
    'imu:CRCError','Extension CRC mismatch.');
sample=struct('Kind',uint8(1+sensor),'Sequence',typecast(data(5:6),'uint16'), ...
    'TimeSeconds',double(typecast(data(7:10),'uint32'))/1000, ...
    'BuildID',typecast(data(11:14),'uint32'),'FirmwareRevision',typecast(data(15:18),'uint32'), ...
    'Values',nan(1,121));
if command
    sample.Values(1:53)=[double(reshape(typecast(data(19:126),'single'),1,27)), ...
        double(data(127:130).'),double(reshape(typecast(data(131:146),'uint32'),1,4)), ...
        double(data(147:156).'),double(typecast(data(157:160),'single')), ...
        double(typecast(data(161:164),'uint32')),double(reshape(typecast(data(165:188),'single'),1,6))];
else
    sample.Values(54:121)=[double(reshape(typecast(data(19:98),'single'),1,20)), ...
        double(reshape(typecast(data(99:122),'uint32'),1,6)), ...
        double(reshape(typecast(data(123:138),'uint16'),1,8)), ...
        double(reshape(typecast(data(139:162),'uint32'),1,6)),double(data(163:168).'), ...
        double(reshape(typecast(data(169:176),'single'),1,2)),double(reshape(typecast(data(177:240),'uint32'),1,16)), ...
        double(data(241:244).')];
end
end
