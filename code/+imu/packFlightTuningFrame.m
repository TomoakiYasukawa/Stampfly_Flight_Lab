function frame = packFlightTuningFrame(sequence,timeSeconds,accel,gyro, ...
        imuValid,tofM,tofValid,tofRangeStatus,flowDelta,flowQuality, ...
        flowStatus,flowShutter,xy,flowUsed,mag,magValid,orientation, ...
        orientationValid,heightM,heightValid,flowDeltaEN,motorCommands, ...
        motorValid,flightState,acceptedCommandSequence,diagnostics,buildID, ...
        tuningTail2,tuningAckSequence,tuningAckStatus,skipCRC)
if nargin < 31,skipCRC=false;end
%PACKFLIGHTTUNINGFRAME SFI8 telemetry with applied tuning and acknowledgement.
% Bytes 1:180 preserve the SFI7 layout (with SFI8 magic). Bytes 181:188
% contain the last two height parameters, command sequence, status, namespace.
base = imu.packFlightDiagnosticsFrame(sequence,timeSeconds,accel,gyro, ...
    imuValid,tofM,tofValid,tofRangeStatus,flowDelta,flowQuality, ...
    flowStatus,flowShutter,xy,flowUsed,mag,magValid,orientation, ...
    orientationValid,heightM,heightValid,flowDeltaEN,motorCommands, ...
    motorValid,flightState,acceptedCommandSequence,diagnostics,buildID,true);
assert(numel(tuningTail2) == 2,'imu:TuningTailShape', ...
    'Expected maximum vertical speed and landing base throttle.');
tail = single(tuningTail2(:));
scales = imu.heightTuningScales();
encoded = zeros(2,1,'int16');
for k = 1:2
    assert(isfinite(tail(k)),'imu:TuningTailValue', ...
        'Applied tuning parameters must be finite.');
    encoded(k) = int16(min(max(round(tail(k)*scales(k+7)), ...
        single(-32767)),single(32767)));
end
frame = zeros(190,1,'uint8');
frame(1:180) = base(1:180);
frame(1:4) = uint8('SFI8');
frame(181:184) = reshape(typecast(encoded,'uint8'),4,1);
frame(185:186) = reshape(typecast(uint16(tuningAckSequence),'uint8'),2,1);
frame(187) = uint8(tuningAckStatus);
frame(188) = uint8(1); % Namespace 1: height-control parameters.
if ~skipCRC
    frame(189:190) = reshape(typecast(imu.crc16(frame(1:188)),'uint8'),2,1);
end
end
