function sample = decodeFrame(frame)
%DECODEFRAME Validate and decode SFI1 through SFI8 telemetry.
data = uint8(frame(:));
isV1 = numel(data) == 37 && isequal(data(1:4),uint8('SFI1').');
isV2 = numel(data) == 63 && isequal(data(1:4),uint8('SFI2').');
isV3 = numel(data) == 93 && isequal(data(1:4),uint8('SFI3').');
isV4 = numel(data) == 106 && isequal(data(1:4),uint8('SFI4').');
isV5 = numel(data) == 111 && isequal(data(1:4),uint8('SFI5').');
isV6 = numel(data) == 114 && isequal(data(1:4),uint8('SFI6').');
isV7 = numel(data) == 182 && isequal(data(1:4),uint8('SFI7').');
isV8 = numel(data) == 190 && isequal(data(1:4),uint8('SFI8').');
assert(isV1 || isV2 || isV3 || isV4 || isV5 || isV6 || isV7 || isV8, ...
    'imu:InvalidFrame','Expected a supported SFI frame (37 to 190 bytes).');
receivedCRC = typecast(data(end-1:end),'uint16');
assert(receivedCRC == imu.crc16(data(1:end-2)), ...
    'imu:CRCError','SFI frame CRC mismatch.');
values = typecast(data(11:34),'single');
sample = struct( ...
    'Version',uint8(1 + isV2 + 2*isV3 + 3*isV4 + 4*isV5 + 5*isV6 + 6*isV7 + 7*isV8), ...
    'Sequence',typecast(data(5:6),'uint16'), ...
    'TimeSeconds',double(typecast(data(7:10),'uint32'))/1000, ...
    'Acceleration',reshape(values(1:3),1,3), ...
    'AngularVelocity',reshape(values(4:6),1,3), ...
    'IMUValid',logical(data(35) ~= 0), ...
    'ToFDistanceM',single(NaN), ...
    'ToFValid',false, ...
    'ToFRangeStatus',uint8(0), ...
    'FlowDelta',single([NaN NaN]), ...
    'FlowQuality',uint8(0), ...
    'FlowStatus',false, ...
    'FlowShutter',uint8(0), ...
    'XYDisplacementM',single([NaN NaN]), ...
    'FlowUsed',false, ...
    'MagneticFieldUT',single([NaN NaN NaN]), ...
    'MagValid',false, ...
    'MagFresh',false, ...
    'Orientation',single([NaN NaN NaN NaN]), ...
    'OrientationValid',false, ...
    'HeightM',single(NaN), ...
    'HeightValid',false, ...
    'FlowCorrectedDeltaENM',single([NaN NaN]), ...
    'MotorCommands',single([NaN NaN NaN NaN]), ...
    'MotorValid',false, ...
    'FlightState',uint8(0), ...
    'AcceptedCommandSequence',uint16(0), ...
    'Diagnostics',single(NaN(1,32)), ...
    'BuildID',uint32(0), ...
    'BatteryVoltageV',single(NaN), ...
    'BatteryValid',false, ...
    'ToFFresh',false, ...
    'AppliedHeightParameters9',single(NaN(1,9)), ...
    'TuningAckSequence',uint16(0), ...
    'TuningAckStatus',uint8(0), ...
    'TuningNamespace',uint8(0));
if isV2 || isV3 || isV4 || isV5 || isV6 || isV7 || isV8
    sample.ToFDistanceM = typecast(data(36:39),'single');
    sample.ToFValid = logical(data(40) ~= 0);
    sample.ToFRangeStatus = data(41);
    sample.FlowDelta = reshape(typecast(data(42:49),'single'),1,2);
    sample.FlowQuality = data(50);
    sample.FlowStatus = logical(data(51) ~= 0);
    sample.FlowShutter = data(52);
    sample.XYDisplacementM = reshape(typecast(data(53:60),'single'),1,2);
    sample.FlowUsed = logical(data(61) ~= 0);
end
if isV3 || isV4 || isV5 || isV6 || isV7 || isV8
    sample.MagneticFieldUT = reshape(typecast(data(62:73),'single'),1,3);
    sample.MagValid = bitand(data(74),uint8(1)) ~= 0;
    sample.MagFresh = bitand(data(74),uint8(2)) ~= 0;
    sample.Orientation = reshape(typecast(data(75:90),'single'),1,4);
    sample.OrientationValid = logical(data(91) ~= 0);
end
if isV4 || isV5 || isV6 || isV7 || isV8
    sample.HeightM = typecast(data(92:95),'single');
    sample.HeightValid = logical(data(96) ~= 0) && ...
        isfinite(sample.HeightM) && sample.HeightM >= 0;
    sample.FlowCorrectedDeltaENM = reshape( ...
        typecast(data(97:104),'single'),1,2);
end
if isV5 || isV6 || isV7 || isV8
    sample.MotorCommands = single(reshape(data(105:108),1,4));
    sample.MotorValid = logical(data(109) ~= 0);
    if ~sample.MotorValid
        sample.MotorCommands(:) = NaN;
    end
end
if isV6 || isV7 || isV8
    sample.FlightState = data(110);
    sample.AcceptedCommandSequence = typecast(data(111:112),'uint16');
end
if isV7 || isV8
    encoded = reshape(typecast(data(113:176),'int16'),1,32);
    values = single(encoded)./reshape(imu.flightDiagnosticScales(),1,32);
    values(encoded == int16(-32768)) = single(NaN);
    sample.Diagnostics = values;
    sample.BuildID = typecast(data(177:180),'uint32');
    sample.BatteryVoltageV = values(1);
    sample.BatteryValid = isfinite(values(1)) && values(2) ~= 0 && ...
        values(1) >= 2.0 && values(1) <= 5.0;
    sample.ToFFresh = isfinite(values(3)) && values(3) ~= 0;
end
if isV8
    encodedTail = reshape(typecast(data(181:184),'int16'),1,2);
    scales = reshape(imu.heightTuningScales(),1,9);
    sample.AppliedHeightParameters9 = [sample.Diagnostics(26:32), ...
        single(encodedTail)./scales(8:9)];
    sample.TuningAckSequence = typecast(data(185:186),'uint16');
    sample.TuningAckStatus = data(187);
    sample.TuningNamespace = data(188);
end
end
