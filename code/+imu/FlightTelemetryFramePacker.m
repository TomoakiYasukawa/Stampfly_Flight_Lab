classdef FlightTelemetryFramePacker < matlab.System
    %FLIGHTTELEMETRYFRAMEPACKER Build SFI8 telemetry at 50 Hz.
    properties (Access = private)
        Sequence = uint16(0)
    end
    methods (Access = protected)
        function frame = stepImpl(obj,accel,gyro,imuValid,timeSeconds, ...
                tofM,tofValid,tofRangeStatus,flowDelta,flowQuality, ...
                flowStatus,flowShutter,xy,flowUsed,mag,magValid, ...
                orientation,orientationValid,heightM,heightValid,flowDeltaEN, ...
                motorCommands,motorValid,flightState,acceptedSequence, ...
                batteryV,batteryValid,tofFresh,heightDiagnostics,rawVz, ...
                mixerBeforeLimit,flightParameters,tuningParameters, ...
                tuningAckSequence,tuningAckStatus,buildID)
            heightDiagnostics = single(heightDiagnostics(:));
            mixerBeforeLimit = single(mixerBeforeLimit(:));
            flightParameters = single(flightParameters(:));
            tuningParameters = single(tuningParameters(:));
            diagnostics = [single(batteryV); single(batteryValid); ...
                single(tofFresh); heightDiagnostics(1:3); single(rawVz); ...
                heightDiagnostics(4:13); ...
                single(heightDiagnostics(11) ~= heightDiagnostics(12)); ...
                mixerBeforeLimit(1:4); flightParameters(1:3); ...
                tuningParameters(1:7)];
            frame = imu.packFlightTuningFrame(obj.Sequence,timeSeconds, ...
                accel,gyro,imuValid,tofM,tofValid,tofRangeStatus, ...
                flowDelta,flowQuality,flowStatus,flowShutter,xy,flowUsed, ...
                mag,magValid,orientation,orientationValid,heightM, ...
                heightValid,flowDeltaEN,motorCommands,motorValid, ...
                flightState,acceptedSequence,diagnostics,buildID, ...
                tuningParameters(8:9),tuningAckSequence,tuningAckStatus);
            obj.Sequence = uint16(bitand(uint32(obj.Sequence)+1,uint32(65535)));
        end
        function resetImpl(obj), obj.Sequence = uint16(0); end
        function n = getNumInputsImpl(~), n = 35; end
        function n = getNumOutputsImpl(~), n = 1; end
        function varargout = getInputNamesImpl(~)
            varargout = {'Accel3','Gyro3','IMUValid','TimeSeconds', ...
                'ToFM','ToFValid','ToFRangeStatus','FlowDelta2', ...
                'FlowQuality','FlowStatus','FlowShutter','EastNorthM2', ...
                'FlowUsed','Mag3','MagValid','Orientation4', ...
                'OrientationValid','HeightM','HeightValid', ...
                'CorrectedDeltaEN2','Motor4','MotorValid', ...
                'FlightState','AcceptedSequence', ...
                'BatteryV','BatteryValid','ToFFresh','HeightDiagnostics13', ...
                'RawVerticalSpeed','MixerBeforeLimit4','FlightParameters3', ...
                'TuningParameters9','TuningAckSequence','TuningAckStatus','BuildID'};
        end
        function name = getOutputNamesImpl(~), name = 'Frame190'; end
        function s = getOutputSizeImpl(~), s = [190 1]; end
        function t = getOutputDataTypeImpl(~), t = 'uint8'; end
        function c = isOutputComplexImpl(~), c = false; end
        function f = isOutputFixedSizeImpl(~), f = true; end
        function st = getSampleTimeImpl(obj)
            st = createSampleTime(obj,'Type','Discrete','SampleTime',0.02);
        end
    end
end
